/**
 * Stackra file contract:
 * Purpose: proves the Assistant panel page sits at /pro-assistant-panel in the AI category, titles the page and the
 *          document, and draws a region named by the assistant's heading with the visible AI label and the composer.
 * Boundary: jsdom with real HeroUI Pro; `matchMedia` and `ResizeObserver` are stubbed because jsdom has neither.
 * Runtime: browser
 * Governing contract: ADR 0360 (decision 11); ADR 0022 (test placement).
 */
import { render, screen } from "@testing-library/react";

import { stubBrowserApis } from "#src/__tests__/stub-browser-apis";
import { ProAssistantPanel } from "#src/routes/pro-assistant-panel/pro-assistant-panel";
import { ProAssistantPanelRoute } from "#src/routes/pro-assistant-panel/pro-assistant-panel.route";
import { routePath } from "#src/components/playground-pages/route-path.function";

describe("ProAssistantPanel", () => {
  beforeEach(stubBrowserApis);
  afterEach(() => vi.unstubAllGlobals());

  it("sits at /pro-assistant-panel in the AI category, and titles the page and the document", () => {
    render(<ProAssistantPanel />);
    expect(routePath(ProAssistantPanelRoute)).toBe("/pro-assistant-panel");
    expect(ProAssistantPanelRoute.category).toBe("AI");
    expect(
      screen.getByRole("heading", { level: 1, name: ProAssistantPanelRoute.title }),
    ).toBeTruthy();
    expect(document.title).toBe("Assistant panel · Stackra Playground");
  });

  it("draws the panel as a region named by its heading, with the AI label and the composer", () => {
    render(<ProAssistantPanel />);
    expect(screen.getByRole("region", { name: "Sidekick" })).toBeTruthy();
    expect(screen.getByText("Answers are generated by AI")).toBeTruthy();
    expect(screen.getByRole("textbox", { name: "Message" })).toBeTruthy();
  });
});
