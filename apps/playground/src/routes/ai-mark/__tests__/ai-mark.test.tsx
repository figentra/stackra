/**
 * Stackra file contract:
 * Purpose: proves the AI mark page sits at /ai-mark in the AI category, titles the page and the document, and draws
 *          the three kinds with their labels read out, the generated one shown as text.
 * Boundary: jsdom with the real `@stackra/ui` web entry.
 * Runtime: browser
 * Governing contract: ADR 0360 (decision 11); ADR 0022 (test placement).
 */
import { render, screen } from "@testing-library/react";

import { AiMark } from "#src/routes/ai-mark/ai-mark";
import { AiMarkRoute } from "#src/routes/ai-mark/ai-mark.route";
import { routePath } from "#src/components/playground-pages/route-path.function";

describe("AiMark page", () => {
  it("sits at /ai-mark in the AI category, and titles the page and the document", () => {
    render(<AiMark />);
    expect(routePath(AiMarkRoute)).toBe("/ai-mark");
    expect(AiMarkRoute.category).toBe("AI");
    expect(screen.getByRole("heading", { level: 1, name: AiMarkRoute.title })).toBeTruthy();
    expect(document.title).toBe("AI mark · Stackra Playground");
  });

  it("reads each kind's label, and shows the generated one", () => {
    render(<AiMark />);
    expect(screen.getByLabelText("Your assistant can do this")).toBeTruthy();
    expect(screen.getByLabelText("Changed by an agent")).toBeTruthy();
    expect(screen.getByText("Answers are generated by AI")).toBeTruthy();
  });
});
