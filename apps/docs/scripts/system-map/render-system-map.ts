/**
 * Stackra file contract:
 * Purpose: `renderSystemMap`, the docs renderer of the system map (STA-845 part 2): from the merged `SystemGraph` it
 *          renders the three levels as Mintlify pages: level 1 the whole system (`index.mdx`: the repos, their services,
 *          the flows, the providers and the gaps), level 2 one flow step by step (`flows/<flow>.mdx`, a sequence
 *          diagram and a step table) and level 3 one service (`services/<repo>/<member>.mdx`: calls and events in and
 *          out, tables, packages, drivers, who uses it, its flows).
 * Boundary: pure and deterministic: graph in, pages out, in the graph's own (sorted) order. Every name, edge and flow
 *           comes from the graph; nothing is listed by hand, so the pages are regenerated, never edited. It reads the
 *           graph shape only through `@stackra/gen`'s exported types (ADR 0452 decision 4). It returns Mintlify MDX;
 *           `write-system-map.ts` runs it and writes the pages.
 * Runtime: node
 * Governing contract: ADR 0452 (the system graph); STA-845 (levels 1 to 3, flows declared once); batch stackra-60
 *                     (STA-1098); under scripts/ since stackra-177 (STA-1317).
 */
import type { GraphFlow, GraphNode, SystemGraph } from "@stackra/gen";

/** One generated page, by its path under the map's folder. */
type SystemMapPage = { readonly path: string; readonly content: string };

/** A node's page path under `services/`: `<repo>/<member>`. */
function slugOf(node: GraphNode): string {
  return `${node.repo}/${node.id.slice(node.repo.length + 1)}`;
}

/** A page: frontmatter, the file contract and the generated-file notice, then the body. */
function page(title: string, description: string, notice: string, body: readonly string[]): string {
  return [
    "---",
    `title: ${JSON.stringify(title)}`,
    `description: ${JSON.stringify(description)}`,
    "---",
    "",
    `{/* Stackra file contract: Purpose: ${description} Boundary: generated by apps/docs/scripts/system-map/write-system-map.ts from the merged system graph; never edit it. Runtime: docs. Governing contract: ADR 0452; STA-845. */}`,
    "",
    `<Note>${text(notice)}</Note>`,
    "",
    ...body,
  ].join("\n");
}

/** Prose safe in MDX: no JSX or expression braces. */
function text(value: string): string {
  return value
    .replaceAll("{", "&#123;")
    .replaceAll("}", "&#125;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

/** A table cell: MDX-safe prose with no pipe or line break. */
function cell(value: string): string {
  return text(value).replaceAll("|", "\\|").replaceAll(/\r?\n/g, " ");
}

/** An inline code span. */
function code(value: string): string {
  return `\`${value.replaceAll("`", "'").replaceAll("|", "\\|")}\``;
}

/** A Mermaid label: quotes as entities, no statement separators. */
function label(value: string): string {
  return value.replaceAll('"', "#quot;").replaceAll(";", ",").replaceAll(/\r?\n/g, " ");
}

/** A GFM table, or `None.` when there are no rows. */
function table(head: readonly string[], rows: readonly (readonly string[])[]): string[] {
  if (rows.length === 0) return ["None.", ""];
  return [
    `| ${head.join(" | ")} |`,
    `| ${head.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
    "",
  ];
}

/** A bulleted list, or `None.`. */
function list(items: readonly string[]): string[] {
  return items.length === 0 ? ["None.", ""] : [...items.map((item) => `- ${item}`), ""];
}

/**
 * The map's pages for `graph`.
 *
 * @param graph - the merged system graph (`mergeSystemGraphs`), or one repo's `stackra.graph.json`.
 * @param options - `base`, the URL the map's folder is served at (default `/system-map`).
 * @example
 * renderSystemMap(graph).map((page) => page.path); // ["flows/checkout.mdx", "index.mdx", "services/os/billing.mdx"]
 */
export function renderSystemMap(
  graph: SystemGraph,
  options: { readonly base?: string } = {},
): SystemMapPage[] {
  const base = options.base ?? "/system-map";
  const nodes = new Map(graph.nodes.map((node) => [node.id, node]));
  const serviceUrl = (node: GraphNode): string => `${base}/services/${slugOf(node)}`;
  const flowUrl = (flow: GraphFlow): string => `${base}/flows/${flow.id}`;
  const flows = new Map(graph.flows.map((flow) => [flow.id, flow]));
  // A node id links to its level 3 page; `actor.*`, `provider.*` and unresolved ids stay plain.
  const ref = (id: string): string => {
    const node = nodes.get(id);
    return node === undefined ? code(id) : `[${code(id)}](${serviceUrl(node)})`;
  };
  const flowRef = (id: string): string => {
    const flow = flows.get(id);
    return flow === undefined ? code(id) : `[${cell(flow.title)}](${flowUrl(flow)})`;
  };
  const notice = graph.$comment;
  const pages: SystemMapPage[] = [];

  // Level 1: the whole system.
  const body: string[] = [];
  if (graph.nodes.length === 0)
    body.push(
      "The graph has no nodes yet: run `stackra gen` in each repo, write each repo graph, then merge them.",
      "",
    );
  else {
    const repoIds = graph.repos.map((repo, index) => [repo, `R${index}`] as const);
    const repoId = new Map(repoIds);
    const between = new Map<string, { calls: number; events: number }>();
    for (const edge of graph.edges) {
      const from = nodes.get(edge.from)?.repo;
      const to = nodes.get(edge.to)?.repo;
      if (from === undefined || to === undefined || from === to) continue;
      const key = `${from} ${to}`;
      const count = between.get(key) ?? { calls: 0, events: 0 };
      if (edge.kind === "call") count.calls += 1;
      else count.events += 1;
      between.set(key, count);
    }
    const bound = graph.nodes.filter((node) => node.drivers.length > 0);
    body.push("```mermaid", "flowchart LR");
    for (const [repo, id] of repoIds) {
      const count = graph.nodes.filter((node) => node.repo === repo).length;
      body.push(`  ${id}["${label(`${repo} (${count} members)`)}"]`);
    }
    if (bound.length > 0) body.push(`  P(["providers"])`);
    // oxlint-disable-next-line unicorn/no-array-sort -- sorts an array built here, which nothing else holds; toSorted is ES2023 and the base lib is ES2022
    for (const [key, count] of [...between].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
      const [from = "", to = ""] = key.split(" ");
      const parts = [
        count.calls > 0 ? `${count.calls} calls` : "",
        count.events > 0 ? `${count.events} events` : "",
      ].filter(Boolean);
      body.push(`  ${repoId.get(from)} -->|"${label(parts.join(", "))}"| ${repoId.get(to)}`);
    }
    // oxlint-disable-next-line unicorn/no-array-sort -- sorts an array built here, which nothing else holds; toSorted is ES2023 and the base lib is ES2022
    for (const repo of [...new Set(bound.map((node) => node.repo))].sort())
      body.push(`  ${repoId.get(repo)} -.->|drivers| P`);
    body.push("```", "");

    for (const repo of graph.repos) {
      body.push(`## ${text(repo)}`, "");
      body.push(
        ...table(
          ["Member", "Layout", "Calls", "Events out", "Events in", "Flows"],
          graph.nodes
            .filter((node) => node.repo === repo)
            .map((node) => [
              ref(node.id),
              cell(node.layout),
              String(node.calls.length),
              String(node.eventsOut.length),
              String(node.eventsIn.length),
              node.flows.map(flowRef).join(", "),
            ]),
        ),
      );
    }
  }

  body.push("## Flows", "");
  body.push(
    ...table(
      ["Flow", "Steps", "Summary"],
      graph.flows.map((flow) => [
        `[${cell(flow.title)}](${flowUrl(flow)})`,
        String(flow.steps.length),
        cell(flow.summary ?? ""),
      ]),
    ),
  );

  const ports = new Map<string, { candidates: Set<string>; by: string[] }>();
  for (const node of graph.nodes)
    for (const driver of node.drivers) {
      const entry = ports.get(driver.port) ?? { candidates: new Set<string>(), by: [] };
      for (const candidate of driver.candidates) entry.candidates.add(candidate);
      entry.by.push(node.id);
      ports.set(driver.port, entry);
    }
  body.push("## Providers", "");
  body.push(
    ...table(
      ["Port", "Drivers", "Bound by"],
      [...ports]
        // oxlint-disable-next-line unicorn/no-array-sort -- sorts an array built here, which nothing else holds; toSorted is ES2023 and the base lib is ES2022
        .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
        .map(([port, entry]) => [
          code(port),
          // oxlint-disable-next-line unicorn/no-array-sort -- sorts an array built here, which nothing else holds; toSorted is ES2023 and the base lib is ES2022
          [...entry.candidates].sort().map(code).join(", "),
          entry.by.map(ref).join(", "),
        ]),
    ),
  );

  body.push("## Gaps", "");
  body.push(...list(graph.gaps.map(text)));
  pages.push({
    path: "index.mdx",
    content: page(
      "System map",
      `The whole system (${graph.repos.join(", ") || "no repos yet"}): members, flows, providers and gaps, generated from the merged system graph.`,
      notice,
      body,
    ),
  });

  // Level 2: one flow, step by step.
  for (const flow of graph.flows) {
    const actors: string[] = [];
    for (const step of flow.steps)
      for (const id of [step.from, step.to]) if (!actors.includes(id)) actors.push(id);
    const actor = (id: string): string => `A${actors.indexOf(id)}`;
    const lines = ["```mermaid", "sequenceDiagram"];
    actors.forEach((id) => lines.push(`  participant ${actor(id)} as ${label(id)}`));
    for (const step of flow.steps)
      lines.push(
        `  ${actor(step.from)}${step.kind === "event" ? "--)" : "->>"}${actor(step.to)}: ${label(step.event === undefined ? step.label : `${step.label} (${step.event})`)}`,
      );
    lines.push("```", "");
    pages.push({
      path: `flows/${flow.id}.mdx`,
      content: page(flow.title, flow.summary ?? `The ${flow.title} flow, step by step.`, notice, [
        `[System map](${base})`,
        "",
        ...lines,
        "## Steps",
        "",
        ...table(
          ["#", "From", "To", "Kind", "What happens", "Event", "Data"],
          flow.steps.map((step, index) => [
            String(index + 1),
            ref(step.from),
            ref(step.to),
            cell(step.kind),
            cell(step.label),
            step.event === undefined ? "" : code(step.event),
            cell(step.data ?? ""),
          ]),
        ),
      ]),
    });
  }

  // Level 3: one service.
  for (const node of graph.nodes) {
    const inbound = graph.edges.filter((edge) => edge.to === node.id);
    const outbound = graph.edges.filter((edge) => edge.from === node.id);
    const others = [
      ...new Set([...inbound.map((edge) => edge.from), ...outbound.map((edge) => edge.to)]),
    ]
      .filter((id) => id !== node.id)
      // oxlint-disable-next-line unicorn/no-array-sort -- sorts an array built here, which nothing else holds; toSorted is ES2023 and the base lib is ES2022
      .sort();
    const other = (id: string): string => (id === node.id ? "S" : `N${others.indexOf(id)}`);
    const arrow = (edge: (typeof graph.edges)[number]): string =>
      edge.kind === "call" ? "-->|call|" : `-.->|"${label(edge.event ?? "event")}"|`;
    const diagram = ["```mermaid", "flowchart LR", `  S["${label(node.id)}"]`];
    others.forEach((id) => diagram.push(`  ${other(id)}["${label(id)}"]`));
    for (const edge of [...inbound, ...outbound])
      diagram.push(`  ${other(edge.from)} ${arrow(edge)} ${other(edge.to)}`);
    diagram.push("```", "");
    const consumers = (wire: string): string =>
      outbound
        .filter((edge) => edge.kind === "event" && edge.event === wire)
        .map((edge) => ref(edge.to))
        .join(", ");
    const publishers = (wire: string): string =>
      inbound
        .filter((edge) => edge.kind === "event" && edge.event === wire)
        .map((edge) => ref(edge.from))
        .join(", ");
    pages.push({
      path: `services/${slugOf(node)}.mdx`,
      content: page(
        node.id,
        `${node.package} (${node.layout}) in ${node.repo}: its calls, events, tables, packages and drivers.`,
        notice,
        [
          `[System map](${base})`,
          "",
          ...table(
            ["Package", "Repo", "Folder", "Layout", "Modules"],
            [
              [
                code(node.package),
                cell(node.repo),
                code(node.path),
                cell(node.layout),
                node.modules.map(code).join(", "),
              ],
            ],
          ),
          ...(others.length === 0 ? [] : diagram),
          "## Calls out",
          "",
          ...list(outbound.filter((edge) => edge.kind === "call").map((edge) => ref(edge.to))),
          "## Called by",
          "",
          ...list(inbound.filter((edge) => edge.kind === "call").map((edge) => ref(edge.from))),
          "## Events published",
          "",
          ...table(
            ["Event", "Consumed by"],
            node.eventsOut.map((wire) => [code(wire), consumers(wire)]),
          ),
          "## Events consumed",
          "",
          ...table(
            ["Event", "Published by"],
            node.eventsIn.map((wire) => [code(wire), publishers(wire)]),
          ),
          "## Tables",
          "",
          ...list(node.tables.map(code)),
          "## Packages",
          "",
          ...list(node.packages.map(code)),
          "## Drivers",
          "",
          ...table(
            ["Port", "Drivers"],
            node.drivers.map((driver) => [
              code(driver.port),
              driver.candidates.map(code).join(", "),
            ]),
          ),
          "## Used by",
          "",
          ...list(node.usedBy.map(ref)),
          "## Flows",
          "",
          ...list(node.flows.map(flowRef)),
        ],
      ),
    });
  }

  // oxlint-disable-next-line unicorn/no-array-sort -- sorts an array built here, which nothing else holds; toSorted is ES2023 and the base lib is ES2022
  return pages.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}
