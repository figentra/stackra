/**
 * Stackra file contract:
 * Purpose: `renderPackageIndex(packages)`, the customer package index (`customers/packages.mdx`): one table per
 *          category, one row per published package with its reference page link, version, `stackra.summary`, entry
 *          points and README and CHANGELOG links.
 * Boundary: pure over the packages' `package.json` facts; it never reads symbols, so the index changes only when a
 *           package is added, renamed, versioned or changes its summary or entries.
 * Runtime: node
 * Governing contract: ADR 0453 (amendment 2026-10-27: the stackra package fields); ADR 0025 (decision 3); ADR 0039;
 *                     STA-1575; STA-2857.
 */
import type { ApiPackage } from "#scripts/api-reference/api-package.type";
import { cell } from "#scripts/api-reference/cell.function";
import { inlineCode } from "#scripts/api-reference/inline-code.function";
import { prose } from "#scripts/api-reference/prose.function";
import { referencePath } from "#scripts/api-reference/reference-path.function";
import { REGENERATE_COMMAND } from "#scripts/api-reference/regenerate-command.constant";

/**
 * The package index page.
 *
 * @param packages - every published package, sorted by category then name (from `listPackages`).
 * @returns the page's MDX, ending with one newline.
 * @example
 * renderPackageIndex(listPackages(root)).includes("## `commerce`"); // true
 */
export function renderPackageIndex(packages: readonly ApiPackage[]): string {
  const lines = [
    "---",
    'title: "API reference"',
    'description: "Every @stackra package: what it is for, its entry points, its generated TypeScript reference, README and changelog."',
    'icon: "library"',
    "---",
    "",
    `{/* Stackra file contract: Purpose: the package index buyers start the API reference from: one row per published @stackra package (package.json name, version, stackra.summary, exports) linking to its generated symbol reference under customers/reference/. Boundary: generated by apps/docs/scripts/api-reference from packages/<category>/<name>/package.json; never edit: run \`${REGENERATE_COMMAND}\`; pnpm validate fails when it differs from what the script writes. Runtime: docs. Governing contract: ADR 0453 (amendment 2026-10-27: the stackra package fields); ADR 0025 (decision 3); ADR 0039; STA-1575; STA-2857. */}`,
    "",
    `Every published \`@stackra\` package (${packages.length}) by category. Select a package for its reference: every exported`,
    "function, class, interface, type and constant of each entry point, with its signature and its TSDoc (parameters,",
    'returns, errors and examples), generated from the source. Import an entry as `import … from "@stackra/<name>/<entry>"`;',
    "`.` is the package name itself.",
    "",
    "<Note>",
    "  HTTP API references for services are generated from their manifests and appear in their own tab when a service",
    "  is published. `@stackra-pro` packages are documented in their own READMEs, delivered inside each tarball.",
    "</Note>",
    "",
  ];
  const categories = [...new Set(packages.map((pkg) => pkg.category))];
  for (const category of categories) {
    lines.push(
      `## ${inlineCode(category)}`,
      "",
      "| Package | Version | Use it for | Entry points | Source |",
      "| ------- | ------- | ---------- | ------------ | ------ |",
    );
    for (const pkg of packages.filter((candidate) => candidate.category === category)) {
      const changelog = `${pkg.sourceUrl.replace("/tree/main/", "/blob/main/")}/CHANGELOG.md`;
      const entries = pkg.entries.map((entry) => inlineCode(entry.subpath)).join(", ") || "—";
      lines.push(
        `| [${inlineCode(pkg.name)}](/${referencePath(pkg.name)}) | ${pkg.version} | ${cell(prose(pkg.summary)) || "—"} | ${cell(entries)} | [README](${pkg.sourceUrl}#readme) · [CHANGELOG](${changelog}) |`,
      );
    }
    lines.push("");
  }
  return `${lines.join("\n").trimEnd()}\n`;
}
