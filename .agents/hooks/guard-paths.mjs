#!/usr/bin/env node
/**
 * PreToolUse (Write|Edit|MultiEdit|NotebookEdit): refuse writes to generated, vendored
 * or secret paths — anything a tool other than the agent owns.
 * PreToolUse (Read|Grep|Glob): refuse only the secrets inbox (ADR 0257); every other read is fine.
 */
import { readStdin, collectStrings, deny, failOpen } from "./_io.mjs";
import { reachesInbox } from "./_inbox.mjs";

const EVENT = "PreToolUse";

const rules = [
  {
    rx: /(^|\/)\.env([./][^/]*)?$/i,
    why: "Secrets guard: .env* files are never written by an agent. Secrets only come from Infisical (developer tokens via the vault); application secrets use Encore secret().",
  },
  {
    rx: /(^|\/)(\.dev\.vars|\.ci-env|\.sentryclirc)$/i,
    why: "Secrets guard: .dev.vars (Wrangler), .ci-env and .sentryclirc hold live tokens and are never written by an agent. A human creates them from Infisical.",
  },
  {
    rx: /(^|\/)(\.secrets\.local\.[^/]+|secrets?\.(json|ya?ml|env|cue)|credentials?\.json|id_(rsa|ed25519)|[^/]+\.(pem|p12|pfx|key))$/i,
    why: "Secrets guard: files with secret-like names are never written by an agent. A human creates them.",
  },
  {
    rx: /(^|\/)pnpm-lock\.yaml$/i,
    why: "pnpm-lock.yaml is written by pnpm. Run `pnpm install` / `pnpm add` instead of editing it.",
  },
  {
    rx: /(^|\/)CHANGELOG\.md$/i,
    why: "CHANGELOG.md is written by Changesets (`pnpm changeset`, then the release job runs `changeset version`). Never hand-edit it.",
  },
  {
    rx: /(^|\/)dist\//i,
    why: "dist/ is build output. Change the source and rebuild.",
  },
  {
    // Encore's generated clients (`~encore/*`) and runtime glue are regenerated by the CLI.
    rx: /(^|\/)(encore\.gen|\.encore)\//i,
    why: "encore.gen/ and .encore/ are generated by the Encore CLI (the `~encore/*` clients resolve from here). Change the source that produces them and re-run `encore run`; never hand-edit generated output.",
  },
  {
    rx: /(^|\/)apps\/mobile\/(ios|android)\//i,
    why: "apps/mobile/ios and android are generated by `expo prebuild`. Change app.json or a config plugin instead.",
  },
  {
    rx: /(^|\/)uniwind-types\.d\.ts$/i,
    why: "uniwind-types.d.ts is generated by Uniwind. Never hand-edit it.",
  },
  {
    // agents-sync projects .agents/agents/** into these; edit the source, not the projection.
    rx: /(^|\/)(\.claude|\.opencode)\/agents\//i,
    why: ".claude/agents and .opencode/agents are generated by agents-sync. Edit the source in .agents/agents and run `pnpm agents:sync`.",
  },
  {
    rx: /(^|\/)\.mcp\.json$/i,
    why: ".mcp.json is generated by agents-sync from .mcp.yaml. Edit .mcp.yaml and run `pnpm agents:sync`.",
  },
];

/** agents-sync's generated rules block markers in the root AGENTS.md. */
const AGENTS_MD_BLOCK = /<!--\s*(BEGIN|END) generated from \.agents\/rules/;

/**
 * ~/Secrets-inbox/ holds values for `pnpm secrets:import`; no tool reads, searches, lists or writes it.
 * An accident guard, not a boundary (ADR 0257): the importer never outputs a value.
 */
const READ_TOOLS = new Set(["Read", "Grep", "Glob"]);
const under = (dir, glob) =>
  glob.startsWith("/") || glob.startsWith("~") ? glob : `${dir}/${glob}`;

async function main() {
  const input = await readStdin();
  const ti = input.tool_input ?? {};
  const str = (v) => (typeof v === "string" && v ? v : undefined);
  const base = str(ti.path) ?? String(input.cwd ?? ".");
  const checks = [
    [ti.file_path, false],
    [ti.notebook_path, false],
    // Grep searches its path recursively; its `glob` filter and Glob's `pattern` are relative to it.
    [input.tool_name === "Grep" ? str(ti.path) : undefined, true],
    [input.tool_name === "Grep" && str(ti.glob) ? under(base, ti.glob) : undefined, false],
    [input.tool_name === "Glob" ? str(ti.path) : undefined, false],
    [input.tool_name === "Glob" && str(ti.pattern) ? under(base, ti.pattern) : undefined, false],
  ].filter(([p]) => str(p));
  const cwd = String(input.cwd ?? "") || undefined; // relative paths and globs resolve against the session cwd
  const hit = checks.find(([p, recursive]) => reachesInbox(p, { recursive, cwd }));
  if (hit)
    deny(
      EVENT,
      `Secrets guard: ~/Secrets-inbox/ holds secret values; no agent reads, searches, lists or writes it. Use \`pnpm secrets:import --list\` (names) and \`pnpm secrets:import\` (import, never prints a value).\nBlocked path: ${hit[0]}`,
    );
  if (READ_TOOLS.has(input.tool_name)) return;

  const target = String(ti.file_path ?? ti.notebook_path ?? "");
  if (!target) return;

  for (const rule of rules) {
    if (rule.rx.test(target)) deny(EVENT, `${rule.why}\nBlocked path: ${target}`);
  }

  // The generated rules block inside the root AGENTS.md is owned by agents-sync. Deny
  // only an edit whose payload touches the BEGIN/END markers or the block content; the
  // hand-written parts of AGENTS.md stay editable.
  if (/(^|\/)AGENTS\.md$/i.test(target)) {
    const touched = collectStrings(input.tool_input ?? {}).join("\n");
    if (AGENTS_MD_BLOCK.test(touched)) {
      deny(
        EVENT,
        `The rules block in AGENTS.md is generated by agents-sync from .agents/rules/** (between the BEGIN/END markers). Edit the source in .agents/rules and run \`pnpm agents:sync\` instead.\nBlocked path: ${target}`,
      );
    }
  }
}

await failOpen(main);
