#!/usr/bin/env node
/**
 * Stackra file contract:
 * Purpose: PreToolUse (Write|Edit|MultiEdit|NotebookEdit): refuse writes to generated, vendored or secret paths — anything a
 * tool other than the agent owns, and source paths whose branch has no answered spec and plan (the plan gate,
 * ADR 0362). PreToolUse (Read|Grep|Glob): refuse the secrets inbox (ADR 0257) and secret files.
 * The path rules live in `_rules.mjs`, shared with the OpenCode guard (ADR 0293); the AGENTS.md block check needs
 * the edit payload, so it stays here.
 * Boundary: reads the hook payload and prints a decision; the path rules live in `_rules.mjs`.
 * Runtime: node (agent hook)
 * Governing contract: ADR 0293; ADR 0257; ADR 0362.
 */
import { readStdin, collectStrings, deny, failOpen } from "./_io.mjs";
import { decidePlanGate, decideRead, decideWrite } from "./_rules.mjs";

const EVENT = "PreToolUse";

/** agents-sync's generated rules block markers in the root AGENTS.md. */
const AGENTS_MD_BLOCK = /<!--\s*(BEGIN|END) generated from \.agents\/rules/;

const READ_TOOLS = new Set(["Read", "Grep", "Glob"]);
const under = (dir, glob) =>
  glob.startsWith("/") || glob.startsWith("~") ? glob : `${dir}/${glob}`;

async function main() {
  const input = await readStdin();
  const ti = input.tool_input ?? {};
  const str = (v) => (typeof v === "string" && v ? v : undefined);
  const base = str(ti.path) ?? String(input.cwd ?? ".");
  const checks = [
    [ti.file_path, false],
    [ti.notebook_path, false],
    // Grep searches its path recursively; its `glob` filter and Glob's `pattern` are relative to it.
    [input.tool_name === "Grep" ? str(ti.path) : undefined, true],
    [input.tool_name === "Grep" && str(ti.glob) ? under(base, ti.glob) : undefined, false],
    [input.tool_name === "Glob" ? str(ti.path) : undefined, false],
    [input.tool_name === "Glob" && str(ti.pattern) ? under(base, ti.pattern) : undefined, false],
  ].filter(([p]) => str(p));
  const cwd = String(input.cwd ?? "") || undefined; // relative paths and globs resolve against the session cwd
  for (const [p, recursive] of checks) {
    const d = decideRead(p, { recursive, cwd });
    if (d.decision === "deny") deny(EVENT, `${d.reason}\nBlocked path: ${p}`);
  }
  if (READ_TOOLS.has(input.tool_name)) return;

  const target = String(ti.file_path ?? ti.notebook_path ?? "");
  if (!target) return;
  const d = decideWrite(target, { cwd });
  if (d.decision === "deny") deny(EVENT, `${d.reason}\nBlocked path: ${target}`);
  const g = await decidePlanGate(target, { cwd });
  if (g.decision === "deny") deny(EVENT, `${g.reason}\nBlocked path: ${target}`);

  // The generated rules block inside the root AGENTS.md is owned by agents-sync. Deny
  // only an edit whose payload touches the BEGIN/END markers or the block content; the
  // hand-written parts of AGENTS.md stay editable.
  if (/(^|\/)AGENTS\.md$/i.test(target)) {
    const touched = collectStrings(input.tool_input ?? {}).join("\n");
    if (AGENTS_MD_BLOCK.test(touched)) {
      deny(
        EVENT,
        `The rules block in AGENTS.md is generated by agents-sync from .agents/rules/** (between the BEGIN/END markers). Edit the source in .agents/rules and run \`pnpm agents:sync\` instead.\nBlocked path: ${target}`,
      );
    }
  }
}

await failOpen(main);
