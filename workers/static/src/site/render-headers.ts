/**
 * Stackra file contract:
 * Purpose: render the Workers static-assets `_headers` file: CORS for every path, immutable caching for each
 *          exact-version schema tree (`/schemas/<x.y.z>/*`).
 * Boundary: pure; returns text. Cloudflare reads the file at deploy time and never serves it.
 * Runtime: node
 * Governing contract: ADR 0284 (hosted static files, decision 4); Cloudflare Workers static assets `_headers`.
 */
import { IMMUTABLE_CACHE_CONTROL, SCHEMAS_PATH } from "#src/constants";

/** Cloudflare's cap on rules in one `_headers` file. */
const MAX_RULES = 100;

/**
 * Render `_headers` for the given release versions.
 *
 * - `/*` gets `Access-Control-Allow-Origin: *`: schemas are public and fetched by editors and validators from any
 *   origin, and a GET with no credentials needs nothing more (no preflight).
 * - Each `/schemas/<version>/*` gets {@link IMMUTABLE_CACHE_CONTROL}. Cache-Control is set only here, never on `/*`, because
 *   Cloudflare joins the values of every matching rule with a comma, which would yield a contradictory header.
 *   Moving paths keep Cloudflare's default (`max-age=0, must-revalidate` plus an ETag).
 *
 * shortcut: one rule per release against a 100-rule cap (99 releases); when a release nears it, move old versions
 * behind one prefix rule or add a Worker script that sets the header.
 *
 * @param versions - every published release version; order is kept.
 * @returns the file's text, ending with a newline.
 * @throws Error when the rules would exceed Cloudflare's cap, so a deploy never silently drops the cache rule.
 */
export function renderHeaders(versions: readonly string[]): string {
  if (versions.length + 1 > MAX_RULES)
    throw new Error(
      `_headers would hold ${versions.length + 1} rules; Cloudflare allows ${MAX_RULES}`,
    );
  const rules = [
    "# Generated by workers/static (src/site/render-headers.ts); edit the generator, not this file.",
    "/*",
    "  Access-Control-Allow-Origin: *",
    "  X-Content-Type-Options: nosniff",
    ...versions.flatMap((version) => [
      `${SCHEMAS_PATH}/${version}/*`,
      `  Cache-Control: ${IMMUTABLE_CACHE_CONTROL}`,
    ]),
  ];
  return `${rules.join("\n")}\n`;
}
