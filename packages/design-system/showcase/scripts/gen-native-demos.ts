/**
 * Stackra file contract:
 * Purpose: `genNativeDemos`: the mobile `demos/index.generated.ts` that maps every entry key ("free/button") to its
 *          demos (`<tier>/<slug>/<id>.tsx`), their sources (`<id>.code.ts`) and a lazy require of its ApiDoc, so the
 *          component screen needs no glob (Metro has none).
 * Boundary: pure; gen.ts writes (or checks) what it returns. Demos follow the entry's example order, then by id.
 * Runtime: node
 * Governing contract: showcase redesign spec (2026-10-27) sections 4 and 7.2 (step 7).
 */
import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";

import type { ComponentEntry } from "../src/types/component-entry.type.ts";

/** PascalCase of a kebab or slash separated key: "free/full-width" -> "FreeFullWidth". */
const pascal = (key: string) =>
  key
    .split(/[^a-z0-9]+/i)
    .filter(Boolean)
    .map((part) => part[0]?.toUpperCase() + part.slice(1))
    .join("");

/** The content of `demos/index.generated.ts` for the demos under `demos` and the ApiDocs under `api`. */
export function genNativeDemos(
  demos: string,
  api: string,
  entries: readonly ComponentEntry[],
): string {
  const order = new Map(
    entries.map((entry) => [`${entry.tier}/${entry.slug}`, entry.examples.map(({ id }) => id)]),
  );
  const imports: string[] = [];
  const rows: string[] = [];
  for (const tier of ["free"]) {
    const dir = join(demos, tier);
    if (!existsSync(dir)) continue;
    for (const slug of readdirSync(dir).toSorted()) {
      if (slug === "__tests__" || !existsSync(join(dir, slug, "."))) continue;
      const key = `${tier}/${slug}`;
      const known = order.get(key) ?? [];
      const ids = readdirSync(join(dir, slug))
        .filter((file) => file.endsWith(".tsx"))
        .map((file) => file.slice(0, -4))
        .toSorted((a, b) => {
          const [ia, ib] = [known.indexOf(a), known.indexOf(b)];
          return (ia < 0 ? Infinity : ia) - (ib < 0 ? Infinity : ib) || a.localeCompare(b);
        });
      if (ids.length === 0) continue;
      const examples = ids.map((id) => {
        const name = pascal(`${key}/${id}`);
        imports.push(
          `import ${name} from "#src/demos/${key}/${id}";`,
          `import ${name}Code from "#src/demos/${key}/${id}.code";`,
        );
        return `      ${JSON.stringify(id)}: { Demo: ${name}, code: ${name}Code },`;
      });
      const apiLine = existsSync(join(api, tier, `${slug}.json`))
        ? [
            "    // oxlint-disable-next-line typescript/no-require-imports -- a lazy require, one JSON per opened screen",
            `    api: () => require("@stackra/showcase/api/native/${key}.json") as ApiDoc,`,
          ]
        : [];
      rows.push(
        `  ${JSON.stringify(key)}: {`,
        "    examples: {",
        ...examples,
        "    },",
        ...apiLine,
        "  },",
      );
    }
  }
  return [
    "/**",
    " * Stackra file contract:",
    ' * Purpose: `DEMOS`, the map from entry key ("free/button") to its native demos, their sources and its ApiDoc, so',
    " *          the component screen needs no glob (Metro has none).",
    " * Boundary: GENERATED by @stackra/showcase gen (gen-native-demos); do not edit by hand.",
    " * Runtime: react-native",
    " * Governing contract: showcase redesign spec (2026-10-27) sections 4 and 7.2 (step 7).",
    " */",
    'import type { ApiDoc } from "@stackra/showcase";',
    "",
    'import type { ComponentDemos } from "#src/components/doc-screen/component-demos.type";',
    ...imports,
    "",
    "/** The native demos by entry key. */",
    "export const DEMOS: Readonly<Record<string, ComponentDemos>> = {",
    ...rows,
    "};",
    "",
  ].join("\n");
}
