/**
 * Stackra file contract:
 * Purpose: proves the native AiMark hands the Icon the sparkles name with the label as its accessible name when the
 *          label is hidden, and a decorative icon plus the label as `Text` when it is shown.
 * Boundary: React Native does not render in vitest: react-native and the package's native Icon and Text are replaced
 *           by recording stand-ins.
 * Runtime: node
 * Governing contract: ADR 0360 (decision 11); ADR 0022 (test placement).
 */
// @vitest-environment jsdom
import { render } from "@testing-library/react";
import type { ReactNode } from "react";

import { AiMark } from "#native/ai-mark/ai-mark";

const received = vi.hoisted(() => ({ props: {} as Record<string, Record<string, unknown>> }));

vi.mock("react-native", async () => {
  const { createElement } = await import("react");
  return {
    View: (props: Record<string, unknown>) =>
      createElement("div", { "data-testid": props["testID"] }, props["children"] as ReactNode),
  };
});
vi.mock("#native/icon/icon", () => ({
  Icon: (props: Record<string, unknown>) => {
    received.props["icon"] = props;
    return null;
  },
}));
vi.mock("#native/text/text", async () => {
  const { createElement } = await import("react");
  return {
    Text: (props: Record<string, unknown>) => {
      received.props["text"] = props;
      return createElement("span", null, props["children"] as ReactNode);
    },
  };
});

describe("AiMark (native)", () => {
  beforeEach(() => {
    received.props = {};
  });

  it("names the icon with the label when the label is hidden", () => {
    const { getByTestId } = render(<AiMark kind="changed" label="Changed by your assistant" />);
    expect(getByTestId("ai-mark-changed")).toBeTruthy();
    expect(received.props["icon"]).toMatchObject({
      name: "sparkles",
      size: "sm",
      label: "Changed by your assistant",
    });
    expect(received.props["text"]).toBeUndefined();
  });

  it("shows the label as text beside a decorative icon", () => {
    const { getByText } = render(
      <AiMark kind="generated" label="Generated by AI" isLabelVisible />,
    );
    expect(getByText("Generated by AI")).toBeTruthy();
    expect(received.props["icon"]?.["label"]).toBeUndefined();
  });
});
