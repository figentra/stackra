/**
 * Stackra file contract:
 * Purpose: writes the files that depend on the installed Lucide set: the `LucideIconName` list in contracts, and per
 *          platform the Lucide components re-exported by name and the full name-to-component registry. Run it
 *          after a Lucide version bump (`pnpm --filter @stackra/icons generate`), then format the output.
 * Boundary: reads the installed `lucide-react` and `lucide-react-native` packages and writes five files under `src/`;
 *          it never touches anything else. The unit tests fail when the committed files drift from the installed set.
 * Runtime: node
 * Governing contract: ADR 0303 (decision 10, the icon model); ADR 0294 (generated files are never edited).
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);

/** The `dist` folder of an installed package: its CommonJS main sits in `dist/cjs`, so one level up. */
const distOf = (name) => dirname(dirname(require.resolve(name)));

const SOURCES = [
  { platform: "react", package: "lucide-react", main: "lucide-react.mjs", runtime: "browser" },
  {
    platform: "native",
    package: "lucide-react-native",
    main: "lucide-react-native.mjs",
    runtime: "react-native",
  },
];

/** The kebab-case file names of the canonical icons in one package (aliases get files of their own on web). */
const iconFiles = (name) =>
  readdirSync(join(distOf(name), "esm", "icons"))
    .filter((file) => file.endsWith(".mjs") && file !== "index.mjs")
    .map((file) => file.slice(0, -".mjs".length));

/** The export names on each `export { default as A, default as B } from './icons/x.mjs'` line, by file name. */
const exportNamesByFile = (source) => {
  const text = readFileSync(join(distOf(source.package), "esm", source.main), "utf8");
  const byFile = new Map();
  for (const [, list, file] of text.matchAll(/export \{ (.+?) \} from '\.\/icons\/(.+?)\.mjs'/g)) {
    byFile.set(
      file,
      [...list.matchAll(/default as (\w+)/g)].map((match) => match[1]),
    );
  }
  return byFile;
};

// The canonical set is what both packages ship as a file of its own: the web package adds alias files on top.
const webFiles = new Set(iconFiles("lucide-react"));
const names = iconFiles("lucide-react-native")
  .filter((name) => webFiles.has(name))
  .sort();

/** The export name of an icon: the first alias whose letters equal the file name's, so not `...Icon` or `Lucide...`. */
const exportNameOf = (name, byFile, packageName) => {
  const letters = name.replaceAll("-", "").toLowerCase();
  // `ArrowDownAZ` and `ArrowDownAz` both match: the first is the one Lucide lists first, in both packages.
  const found = (byFile.get(name) ?? []).filter((alias) => alias.toLowerCase() === letters);
  if (found.length === 0) throw new Error(`${packageName}: no export name for ${name}`);
  return found[0];
};

const perPlatform = SOURCES.map((source) => {
  const byFile = exportNamesByFile(source);
  return names.map((name) => exportNameOf(name, byFile, source.package));
});
// Both packages must agree on every export name, so one generated shape serves both platforms.
names.forEach((name, index) => {
  if (perPlatform[0][index] !== perPlatform[1][index])
    throw new Error(`export names differ: ${name}`);
});
const componentNames = perPlatform[0];

/** The header every generated file starts with, ending in the do-not-edit notice. */
const header = ({ purpose, boundary, runtime, contract }) =>
  [
    "/**",
    " * Stackra file contract:",
    ` * Purpose: ${purpose}`,
    ` * Boundary: ${boundary} Generated by \`scripts/generate-icons.mjs\` from the installed Lucide set: do not`,
    " *          edit, run `pnpm --filter @stackra/icons generate` after a Lucide bump.",
    ` * Runtime: ${runtime}`,
    ` * Governing contract: ${contract}`,
    " */",
  ].join("\n");

const write = (path, text) => writeFileSync(join(root, "src", path), `${text}\n`);

write(
  "contracts/enums/lucide-icon-name.enum.ts",
  [
    header({
      purpose:
        "the name of every icon in the pinned Lucide set, in kebab-case: the one list that `IconName`, `isIconName`\n *          and both platforms' registries are checked against.",
      boundary:
        "the names only; no component is imported, so the leaf stays free of an icon library.",
      runtime: "isomorphic",
      contract: "ADR 0303 (decision 10); ADR 0294 (decision 15, contracts are a leaf).",
    }),
    "",
    "/** The Lucide icon names, sorted, as a frozen tuple. */",
    "// shortcut: a frozen tuple until @stackra/contracts ships Enum.of (ADR 0128); the names carry no labels.",
    "export const LucideIconName = Object.freeze([",
    ...names.map((name) => `  ${JSON.stringify(name)},`),
    "] as const);",
    "",
    "/** One Lucide icon name, the string a declaration holds and the wire carries. */",
    "export type LucideIconName = (typeof LucideIconName)[number];",
  ].join("\n"),
);

for (const source of SOURCES) {
  const where = source.platform;
  write(
    `${where}/lucide-icons/lucide-icons.ts`,
    [
      header({
        purpose: `every Lucide component of \`${source.package}\`, re-exported by its own name, so an app can build a registry\n *          of only the icons it uses without importing the icon library itself.`,
        boundary: "re-exports only; a bundler keeps just the names a registry imports.",
        runtime: source.runtime,
        contract: "ADR 0303 (decision 10); ADR 0165 (Lucide).",
      }),
      "",
      "export {",
      ...componentNames.map((name) => `  ${name},`),
      `} from ${JSON.stringify(source.package)};`,
    ].join("\n"),
  );
  const constant = `LUCIDE_${where.toUpperCase()}_ICONS`;
  write(
    `${where}/lucide-registry/lucide-registry.ts`,
    [
      header({
        purpose: `the whole Lucide set of \`${source.package}\` as one registry keyed by \`IconName\`: the opt-in for an app that\n *          wants every icon.`,
        boundary:
          "importing it puts every icon in the bundle, about 180 KB gzipped on web; an app that cares registers\n *          only the icons it uses.",
        runtime: source.runtime,
        contract: "ADR 0303 (decision 10); ADR 0183 (budgets).",
      }),
      `import type { LucideIconName } from "#contracts/enums/lucide-icon-name.enum";`,
      `import type { IconComponent } from "#contracts/types/icon-component.type";`,
      "",
      `import * as lucide from "#${where}/lucide-icons/lucide-icons";`,
      "",
      `/** Every Lucide icon of \`${source.package}\` by name; importing this module puts all of them in the bundle. */`,
      `export const ${constant}: Readonly<Record<LucideIconName, IconComponent>> = Object.freeze({`,
      ...names.map((name, index) => `  ${JSON.stringify(name)}: lucide.${componentNames[index]},`),
      "});",
    ].join("\n"),
  );
}

console.log(`wrote ${names.length} icon names`);
