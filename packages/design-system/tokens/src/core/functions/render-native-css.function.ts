/**
 * Stackra file contract:
 * Purpose: renders a theme to the Uniwind theme HeroUI Native reads: the radii in `@theme`, and the colour roles
 *          and shadows in `@layer theme { :root { @variant light { … } @variant dark { … } } }`, the shape HeroUI
 *          Native's theming docs and Uniwind's custom-theme docs prescribe. Both variants define the same variables.
 *          It also restyles HeroUI Native's text classes (`.text__root--type-*`) in the theme's type scale, in px,
 *          and writes the Arabic twins as `.type-<token>-ar` classes for the native Text to add.
 * Boundary: a pure function from a Theme to a string; it validates nothing (`defineTheme` does) and writes no file.
 *          The palette, fonts, spacing and motion are web-only: native components read the roles. Font weight is left
 *          to HeroUI Native's `font-*` classes, because with custom fonts a weight selects a family there.
 * Runtime: isomorphic
 * Governing contract: ADR 0302 (Stackra Design System); ADR 0165 (HeroUI Native and Uniwind on native).
 */
import { ColorRole } from "#contracts/enums/color-role.enum";
import type { Theme, TypographyToken } from "#contracts/types/theme.type";
import { HEROUI_TYPOGRAPHY_TOKENS } from "#core/constants/heroui-typography-tokens.constant";

const SHADOWS = ["surface", "overlay", "field"] as const;

/** A number as CSS prints it: two decimals at most (so 40 * 1.1 is 44, not 44.00000000000001), and no `-0`. */
const px = (value: number) => `${Math.round(value * 100) / 100 || 0}px`;

/**
 * The size, line height and letter spacing of a type token in absolute px, which is all React Native takes (no `font`
 * shorthand, no unitless line height, no `em`). `defineTheme` guarantees a px size, a unitless or px line height and
 * a zero, `em` or px letter spacing.
 */
function absoluteStyle({ size, lineHeight, letterSpacing }: TypographyToken): string[] {
  const fontSize = Number.parseFloat(size);
  const lineHeightPx = lineHeight.endsWith("px")
    ? Number.parseFloat(lineHeight)
    : fontSize * Number.parseFloat(lineHeight);
  const letterSpacingPx = letterSpacing.endsWith("em")
    ? fontSize * Number.parseFloat(letterSpacing)
    : Number.parseFloat(letterSpacing);
  return [
    `  font-size: ${px(fontSize)};`,
    `  line-height: ${px(lineHeightPx)};`,
    `  letter-spacing: ${px(letterSpacingPx)};`,
  ];
}

/** The native stylesheet of `theme`, to load after `@import "heroui-native/styles"` in the Uniwind entry CSS. */
export function renderNativeCss(theme: Theme): string {
  const variant = (mode: "light" | "dark") =>
    [
      `    @variant ${mode} {`,
      ...ColorRole.map((role) => `      --${role}: ${theme.colors[role][mode]};`),
      ...SHADOWS.map((shadow) => `      --${shadow}-shadow: ${theme.shadows[shadow][mode]};`),
      "    }",
    ].join("\n");

  return `${[
    `/* Generated by @stackra/tokens from the "${theme.name}" theme: change the theme, not this file. */`,
    `@theme {\n  --radius: ${theme.radius.base};\n  --field-radius: ${theme.radius.field};\n}`,
    `@layer theme {\n  :root {\n${variant("light")}\n\n${variant("dark")}\n  }\n}`,
    ...HEROUI_TYPOGRAPHY_TOKENS.flatMap(({ type, token }) => {
      const latin = theme.typography[token];
      const arabic = theme.typography[`${token}-ar`];
      return [
        ...(latin ? [`.text__root--type-${type} {\n${absoluteStyle(latin).join("\n")}\n}`] : []),
        ...(arabic ? [`.type-${token}-ar {\n${absoluteStyle(arabic).join("\n")}\n}`] : []),
      ];
    }),
  ].join("\n\n")}\n`;
}
