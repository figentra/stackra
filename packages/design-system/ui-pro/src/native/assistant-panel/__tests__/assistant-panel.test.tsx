/**
 * Stackra file contract:
 * Purpose: proves the native AssistantPanel draws the title as a level-2 heading, the AI label shown through `AiMark`
 *          only when a disclosure is given, the header actions, and the conversation above the composer.
 * Boundary: React Native does not render in vitest: react-native and `@stackra/ui/native` are replaced by stand-ins
 *           that render plain DOM, so what reaches them is checked, not their rendering.
 * Runtime: node
 * Governing contract: ADR 0360 (decisions 1 and 11); ADR 0022 (test placement).
 */
// @vitest-environment jsdom
import { render, screen } from "@testing-library/react";
import type { ReactNode } from "react";

import { AssistantPanel } from "#native/assistant-panel/assistant-panel";

vi.mock("react-native", () => ({
  View: ({ children, testID }: { children?: ReactNode; testID?: string }) => (
    <div data-testid={testID}>{children}</div>
  ),
}));
vi.mock("@stackra/ui/native", () => ({
  Heading: ({ children, level }: { children?: ReactNode; level: number }) => (
    <h2 data-level={level}>{children}</h2>
  ),
  AiMark: ({ label, kind }: { label: string; kind: string }) => (
    <span data-testid={`ai-mark-${kind}`}>{label}</span>
  ),
}));

describe("AssistantPanel (native)", () => {
  it("draws the heading, the AI label, the actions, the conversation and the composer", () => {
    render(
      <AssistantPanel
        title="Sidekick"
        disclosure="Answers are generated by AI"
        headerActions={<button type="button">Close</button>}
        composer={<input aria-label="Message" />}
      >
        <p>Hello</p>
      </AssistantPanel>,
    );
    expect(screen.getByRole("heading", { name: "Sidekick" }).dataset["level"]).toBe("2");
    expect(screen.getByTestId("ai-mark-generated").textContent).toBe("Answers are generated by AI");
    expect(screen.getByRole("button", { name: "Close" })).toBeTruthy();
    expect(screen.getByTestId("assistant-panel-conversation").textContent).toBe("Hello");
    expect(screen.getByTestId("assistant-panel-composer").querySelector("input")).toBeTruthy();
  });

  it("draws no AI label without a disclosure", () => {
    render(
      <AssistantPanel title="Sidekick" composer={null}>
        {null}
      </AssistantPanel>,
    );
    expect(screen.queryByTestId("ai-mark-generated")).toBeNull();
  });
});
