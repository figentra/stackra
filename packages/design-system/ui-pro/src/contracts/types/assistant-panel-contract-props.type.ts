/**
 * Stackra file contract:
 * Purpose: the props of the `AssistantPanel`: the sidekick's panel: its title (the product's assistant name), the AI
 *          label shown to people who must know they talk to AI, header actions, the conversation and the composer.
 * Boundary: types only; the panel lays out what it is given. The conversation and composer are the caller's
 *           (`ChatConversation`, `PromptInput`).
 * Runtime: isomorphic
 * Governing contract: ADR 0360 (decisions 1 and 11: one sidekick; customer-facing AI is labelled); ADR 0310 (decision 3).
 */
import type { ReactNode } from "react";

/** Props of the `AssistantPanel`. */
export interface AssistantPanelContractProps {
  /** The assistant's name, the panel's heading. */
  readonly title: ReactNode;
  /** The visible AI label (`Answers are generated by AI`); required wherever end consumers use it. */
  readonly disclosure?: string | undefined;
  /** Buttons in the header (new conversation, close). */
  readonly headerActions?: ReactNode | undefined;
  /** The conversation. */
  readonly children: ReactNode;
  /** The message composer, pinned under the conversation. */
  readonly composer: ReactNode;
}
