/**
 * Stackra file contract:
 * Purpose: proves the web AssistantPanel is a region named by the assistant's name, shows the AI label when given and
 *          none otherwise, and lays out the header actions, the conversation and the composer.
 * Boundary: jsdom; the AI mark is @stackra/ui's real component.
 * Runtime: browser
 * Governing contract: ADR 0360 (decisions 1 and 11); ADR 0022 (test placement).
 */
// @vitest-environment jsdom
import { render, screen } from "@testing-library/react";

import { AssistantPanel } from "#react/assistant-panel/assistant-panel";

describe("AssistantPanel (web)", () => {
  it("is a region named by the assistant, with its parts", () => {
    render(
      <AssistantPanel
        title="Sidekick"
        disclosure="Answers are generated by AI"
        headerActions={<button type="button">Close</button>}
        composer={<textarea aria-label="Message" />}
      >
        <p>Hello</p>
      </AssistantPanel>,
    );
    expect(screen.getByRole("region", { name: "Sidekick" })).toBeTruthy();
    expect(screen.getByText("Answers are generated by AI")).toBeTruthy();
    expect(screen.getByRole("button", { name: "Close" })).toBeTruthy();
    expect(screen.getByText("Hello")).toBeTruthy();
    expect(screen.getByRole("textbox", { name: "Message" })).toBeTruthy();
  });

  it("shows no AI label when none is given", () => {
    render(
      <AssistantPanel title="Sidekick" composer={null}>
        {null}
      </AssistantPanel>,
    );
    expect(document.querySelector("[data-slot='ai-mark']")).toBeNull();
  });
});
