/** Write tools (Write, Edit, MultiEdit, NotebookEdit; OpenCode edit): the inbox, then `WRITE_RULES`. */
export function decideWrite(path, { cwd } = {}) {
  if (reachesInbox(path, { cwd })) return { decision: "deny", reason: INBOX_WHY };
  const rule = WRITE_RULES.find((r) => r.rx.test(path));
  return rule ? { decision: "deny", reason: rule.why } : { decision: "allow", reason: "" };
}

/**
 * Repo-relative source paths an agent writes only with an answered spec and a plan: packages, services, workers,
 * apps and tools, except the docs app and its scaffold template. Everything else (specs, docs, notes) is free.
 */
export const PLAN_GATED =
  /^(?:packages|services|workers)\/|^apps\/(?!docs\/)|^tools\/(?!scaffold\/templates\/apps\/docs\/)/;

/** agents-sync's generated rules block markers in the root AGENTS.md. */
const AGENTS_MD_BLOCK = /<!--\s*(BEGIN|END) generated from \.agents\/rules/;

/** The engine's reading of the rules above: a hit's reason, else false. */
const denied = (/** @type {{ decision: string, reason: string }} */ d) =>
  d.decision === "deny" && d.reason;

/** @type {import("@figentra-oss/flow/guard").PathRule[]} */
export const PATH_RULES = [
  {
    id: "secrets-read",
    reason: INBOX_WHY,
    match: (path, cwd, { recursive }) => denied(decideRead(path, { cwd, recursive })),
  },
  {
    id: "owned-write",
    reason: INBOX_WHY,
    writes: true,
    match: (path, cwd) => denied(decideWrite(path, { cwd })),
  },
  {
    // The generated rules block inside the root AGENTS.md is owned by agents-sync. Deny only an edit whose payload
    // touches the BEGIN/END markers or the block content; the hand-written parts of AGENTS.md stay editable.
    id: "agents-md-block",
    reason:
      "The rules block in AGENTS.md is generated by agents-sync from .agents/rules/** (between the BEGIN/END markers). Edit the source in .agents/rules and run `fflow sync` instead.",
    writes: true,
    match: (path, _cwd, { input }) =>
      /(^|\/)AGENTS\.md$/i.test(path) && AGENTS_MD_BLOCK.test(collectStrings(input).join("\n")),
  },
  ...NEUTRAL,
];
