/**
 * Stackra file contract:
 * Purpose: `checkMiseActionVersion(files)`, the `mise-action-version` rule: every `jdx/mise-action` step, in a workflow
 *          or a composite action, names mise's `version`, and every step names the same one. Without it the action
 *          downloads whichever mise it cached, so one unavailable release asset (GitHub answered 504 for 2026.11.2)
 *          failed every run; with two versions, jobs install different toolchains.
 * Boundary: pure over `[path, text]` pairs; a file that does not parse is skipped (another rule reports it), and so is
 *           one `fflow sync` writes (its first line says so): Flow pins mise in its own template, and a hand edit fails
 *           Flow's gate.
 * Runtime: node
 * Governing contract: ADR 0027 (the toolchain pinned through mise); ADR 0019 (supply-chain hardening).
 */
import { parse } from "yaml";

type Node = { readonly [key: string]: unknown };

/** The header `fflow sync` opens a generated file with. */
const FFLOW_GENERATED = /^# Generated by fflow\b/;

/** The step `uses` of mise's GitHub action, at any ref. */
const MISE_ACTION = /^jdx\/mise-action@/;

/** The steps of a workflow's jobs, or of a composite action. */
function stepsOf(document: Node): Node[] {
  const jobs = Object.values((document["jobs"] ?? {}) as Node) as Node[];
  const runs = (document["runs"] ?? {}) as Node;
  return [
    ...jobs.flatMap((job) => (job["steps"] ?? []) as Node[]),
    ...((runs["steps"] ?? []) as Node[]),
  ];
}

/**
 * The findings for mise-action steps with no `version`, or whose versions differ.
 *
 * @param files - `[path, text]` of each workflow and composite action.
 * @example
 * checkMiseActionVersion([[".github/workflows/ci.yml", "jobs:\n  a:\n    steps:\n      - uses: jdx/mise-action@v5\n"]]);
 * // [".github/workflows/ci.yml: a jdx/mise-action step names no `version` …"]
 */
export function checkMiseActionVersion(files: readonly (readonly [string, string])[]): string[] {
  const findings: string[] = [];
  const versions = new Map<string, string[]>();
  for (const [path, text] of files) {
    if (FFLOW_GENERATED.test(text)) continue;
    let document: unknown;
    try {
      document = parse(text);
    } catch {
      continue;
    }
    if (document === null || typeof document !== "object") continue;
    for (const step of stepsOf(document as Node)) {
      if (typeof step["uses"] !== "string" || !MISE_ACTION.test(step["uses"])) continue;
      const version = ((step["with"] ?? {}) as Node)["version"];
      if (typeof version !== "string" && typeof version !== "number") {
        findings.push(
          `${path}: a jdx/mise-action step names no \`version\`; the action then downloads whichever mise it cached`,
        );
        continue;
      }
      versions.set(String(version), [...(versions.get(String(version)) ?? []), path]);
    }
  }
  if (versions.size > 1)
    findings.push(
      `jdx/mise-action steps pin different mise versions (${[...versions.entries()]
        .map(([version, paths]) => `${version} in ${[...new Set(paths)].join(", ")}`)
        .join("; ")}); pin one`,
    );
  return findings;
}
