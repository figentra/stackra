/**
 * Stackra file contract:
 * Purpose: `checkDocFile(path, text)`, the doc-standard check (ADR 0007, amended 2026-10-21) of one source file: the contract
 *          header, a TSDoc block on exported symbols (inline, through a local `export { … }` list or `export default`),
 *          exported interface and type-literal members, public and protected class members, enum and const-object enum
 *          members and DI token constants, and no types inside doc tags.
 * Boundary: parses with the TypeScript 6 compiler API and never type-checks; never judges the wording of a block. A
 *           generated migration (`// generated by stackra db diff`) is skipped.
 * Runtime: node
 * Governing contract: ADR 0007 (amendment 2026-10-21); ADR 0128.
 */
import ts from "typescript6";

import { KIND_FOLDERS } from "#node/constants/kind-folders.constant";

/** The marker every contract header carries (ADR 0007, decision 1). */
const CONTRACT = "Stackra file contract:";
/** First-line marker of a generated migration, which the doc-standard check skips. */
const GENERATED_MIGRATION = /^\/\/ generated by stackra db diff\r?\n/;
const MIGRATION = KIND_FOLDERS.find((k) => k.folder === "migrations");
/** The header fields ADR 0007 requires, in order. */
const FIELDS = ["Purpose", "Boundary", "Runtime", "Governing contract"];
/** The only values the `Runtime:` field may take. */
const RUNTIMES = ["node", "browser", "worker", "react-native", "isomorphic"];
/** A tag whose braces hold a type: TypeScript owns types, so a doc tag never carries one. */
const TYPED_TAG = /@(?:param|arg|argument|returns?|throws|property|prop)\s*\{/g;
/** A summary shorter than this many words is a label, not a purpose sentence. */
const MIN_SUMMARY_WORDS = 3;
/** An enum member's summary may be a one-word label (`Grams.`): the enum's own block carries the purpose. */
const MIN_ENUM_MEMBER_WORDS = 1;

/** Formats a node position as `path:line`. */
type At = (pos: number) => string;

/** A member that carries a name the finding prints. */
type Named = ts.Node & { readonly name?: ts.Node | undefined };

/** True for a file in a `migrations/` folder with the `.migration` suffix (kind-folder definition). */
const isMigration = (path: string): boolean =>
  MIGRATION !== undefined &&
  path.includes(`/${MIGRATION.folder}/`) &&
  new RegExp(`\\.${MIGRATION.suffix}\\.tsx?$`).test(path);

/** The header problem, or undefined when the first comment is a well-formed contract header (ADR 0007, decision 1). */
function checkHeader(text: string): string | undefined {
  const first = ts.getLeadingCommentRanges(text, 0)?.[0];
  const header = first ? text.slice(first.pos, first.end) : "";
  if (!header.startsWith("/**") || !header.includes(CONTRACT))
    return `missing the Stackra file contract header before the imports (ADR 0007)`;
  for (const field of FIELDS) {
    if (!new RegExp(`^\\s*\\*?\\s*${field}:`, "m").test(header))
      return `contract header has no "${field}:" field (ADR 0007)`;
  }
  const runtime = /^\s*\*?\s*Runtime:[ \t]*(.*)$/m.exec(header)?.[1]?.trim() ?? "";
  if (!RUNTIMES.includes(runtime))
    return `contract header Runtime must be one of ${RUNTIMES.join(", ")} (ADR 0007)`;
  return undefined;
}

/**
 * The TSDoc block of `node`: the last `/** … *\/` block before it, with only line comments and whitespace between. A
 * contract header never counts as a doc block.
 */
function docOf(sf: ts.SourceFile, text: string, node: ts.Node): string | undefined {
  const comments = ts.getLeadingCommentRanges(text, node.pos) ?? [];
  // oxlint-disable-next-line unicorn/prefer-array-find -- reason: findLast is ES2023 and the base lib is ES2022
  const block = comments.filter((c) => text.startsWith("/**", c.pos)).at(-1);
  if (!block) return undefined;
  const between = text.slice(block.end, node.getStart(sf)).replaceAll(/\/\/[^\n]*/g, "");
  if (between.trim() !== "") return undefined;
  const body = text.slice(block.pos, block.end);
  return body.includes(CONTRACT) ? undefined : body;
}

/** The summary (the text before the first tag) must be a sentence of at least `minWords` words, not a label. */
function summaryProblem(doc: string, minWords = MIN_SUMMARY_WORDS): string | undefined {
  const lines = doc
    .replaceAll(/^\/\*\*|\*\/$/g, "")
    .split("\n")
    .map((line) => line.replace(/^\s*\*?\s?/, ""));
  // Only a tag that starts a line ends the summary; `@stackra/logger` mid-sentence is prose.
  const tagAt = lines.findIndex((line) => /^@\w/.test(line.trim()));
  const summary = (tagAt === -1 ? lines : lines.slice(0, tagAt)).join(" ").trim();
  return summary.split(/\s+/).filter(Boolean).length < minWords
    ? "has a TSDoc block without a purpose sentence (ADR 0007)"
    : undefined;
}

/** Pushes a finding unless `node` carries a TSDoc block with a purpose sentence. */
function requireDoc(
  findings: string[],
  at: At,
  sf: ts.SourceFile,
  text: string,
  node: ts.Node,
  label: string,
  minWords = MIN_SUMMARY_WORDS,
): void {
  const doc = docOf(sf, text, node);
  const problem = doc ? summaryProblem(doc, minWords) : "has no TSDoc block (ADR 0007)";
  if (problem) findings.push(`${at(node.getStart(sf))}: ${label} ${problem}`);
}

/** Requires a TSDoc block on each member of an owner (an exported interface, type literal or class). */
function requireMembers(
  findings: string[],
  at: At,
  sf: ts.SourceFile,
  text: string,
  owner: string,
  members: readonly Named[],
  minWords = MIN_SUMMARY_WORDS,
): void {
  for (const member of members) {
    const name = member.name?.getText(sf) ?? "[computed]";
    requireDoc(findings, at, sf, text, member, `${owner}.${name}`, minWords);
  }
}

/** The property and method signatures of an interface or type literal. */
function signatureMembers(members: ts.NodeArray<ts.TypeElement>): ts.TypeElement[] {
  return members.filter((m) => ts.isPropertySignature(m) || ts.isMethodSignature(m));
}

/** True when `node` carries a modifier of `kind`. */
function hasModifier(node: ts.Node, kind: ts.SyntaxKind): boolean {
  const { modifiers } = node as { readonly modifiers?: ts.NodeArray<ts.ModifierLike> };
  return modifiers?.some((m) => m.kind === kind) ?? false;
}

/** A class member that is not part of the exported surface: `private` or a `#name`. */
function isInternalMember(member: ts.ClassElement): boolean {
  return (
    hasModifier(member, ts.SyntaxKind.PrivateKeyword) ||
    member.name?.kind === ts.SyntaxKind.PrivateIdentifier
  );
}

/** The declared name of a statement, when it has a plain identifier name. */
function declaredName(stmt: ts.Statement): string | undefined {
  const { name } = stmt as Named;
  return name && ts.isIdentifier(name) ? name.text : undefined;
}

/**
 * The local names a file exports without an `export` modifier: `export { a, b as c }` (no `from`), `export default a`
 * and `export = a`. A re-export from another module is that module's to document.
 */
function exportedByList(sf: ts.SourceFile): Set<string> {
  const names = new Set<string>();
  for (const stmt of sf.statements) {
    if (
      ts.isExportDeclaration(stmt) &&
      !stmt.moduleSpecifier &&
      stmt.exportClause &&
      ts.isNamedExports(stmt.exportClause)
    ) {
      for (const spec of stmt.exportClause.elements)
        names.add((spec.propertyName ?? spec.name).text);
    }
    if (ts.isExportAssignment(stmt) && ts.isIdentifier(stmt.expression))
      names.add(stmt.expression.text);
  }
  return names;
}

/** Strips parentheses, `as`, `satisfies` and non-null wrappers off an expression. */
function unwrap(expr: ts.Expression): ts.Expression {
  let node = expr;
  while (
    ts.isParenthesizedExpression(node) ||
    ts.isAsExpression(node) ||
    ts.isSatisfiesExpression(node) ||
    ts.isNonNullExpression(node)
  )
    node = node.expression;
  return node;
}

/** True for `x as const`, through any parentheses or `satisfies` around it. */
function isAsConst(expr: ts.Expression): boolean {
  let node = expr;
  while (
    ts.isParenthesizedExpression(node) ||
    ts.isSatisfiesExpression(node) ||
    ts.isAsExpression(node)
  ) {
    if (ts.isAsExpression(node) && ts.isConstTypeReference(node.type)) return true;
    node = node.expression;
  }
  return false;
}

/** True for a `key: "text"` or `key: 1` entry, the shape of a const-object enum member. */
const isLiteralEntry = (p: ts.ObjectLiteralElementLike): boolean =>
  ts.isPropertyAssignment(p) &&
  (ts.isStringLiteralLike(p.initializer) || ts.isNumericLiteral(p.initializer));

/**
 * The object literal of a const-object enum (ADR 0007 amendment; the enum keyword is banned): `Enum.of({ … })` or
 * `{ … } as const` whose values are all string or number literals.
 */
function constEnumObject(decl: ts.VariableDeclaration): ts.ObjectLiteralExpression | undefined {
  if (!decl.initializer) return undefined;
  const init = unwrap(decl.initializer);
  if (
    ts.isCallExpression(init) &&
    ts.isPropertyAccessExpression(init.expression) &&
    init.expression.getText() === "Enum.of"
  ) {
    const arg = init.arguments[0] && unwrap(init.arguments[0]);
    return arg && ts.isObjectLiteralExpression(arg) ? arg : undefined;
  }
  if (!ts.isObjectLiteralExpression(init) || !isAsConst(decl.initializer)) return undefined;
  return init.properties.length > 0 && init.properties.every(isLiteralEntry) ? init : undefined;
}

/** True when a variable is a DI token, `defineToken(...)` (ADR 0007 amendment, decision 2). */
function isDefineToken(decl: ts.VariableDeclaration): boolean {
  const init = decl.initializer;
  return (
    init !== undefined &&
    ts.isCallExpression(init) &&
    ts.isIdentifier(init.expression) &&
    init.expression.text === "defineToken"
  );
}

/**
 * The doc-standard findings of one source file, as `path:line: message` strings.
 *
 * @param path - repository-relative path; picks the parser script kind from its extension.
 * @param text - the file's full contents.
 * @example
 * checkDocFile("packages/x/src/core/a.ts", "export const a = 1;\n"); // header and TSDoc findings
 */
export function checkDocFile(path: string, text: string): string[] {
  // Generated migrations carry no contract header and are rewritten by `stackra db diff`.
  if (isMigration(path) && GENERATED_MIGRATION.test(text)) return [];
  const kind = path.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const sf = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, kind);
  const at: At = (pos) => `${path}:${sf.getLineAndCharacterOfPosition(pos).line + 1}`;
  const findings: string[] = [];

  const headerProblem = checkHeader(text);
  if (headerProblem) findings.push(`${path}:1: ${headerProblem}`);

  for (const match of text.matchAll(TYPED_TAG)) {
    const line = sf.getLineAndCharacterOfPosition(match.index).line + 1;
    findings.push(
      `${path}:${line}: ${match[0]} carries a type; name the parameter and describe it, TypeScript owns the type (ADR 0007)`,
    );
  }

  const listed = exportedByList(sf);
  for (const stmt of sf.statements) {
    if (ts.isExportAssignment(stmt)) {
      // `export default <expr>` documents the expression; `export default name` documents `name` where it is declared.
      if (!ts.isIdentifier(stmt.expression))
        requireDoc(findings, at, sf, text, stmt, "export default");
      continue;
    }
    const inline = hasModifier(stmt, ts.SyntaxKind.ExportKeyword);
    if (!inline && !ts.isVariableStatement(stmt) && !listed.has(declaredName(stmt) ?? "")) continue;
    if (ts.isVariableStatement(stmt)) {
      for (const decl of stmt.declarationList.declarations) {
        const name = decl.name.getText(sf);
        if (!inline && !listed.has(name)) continue;
        const members = constEnumObject(decl);
        if (members)
          requireMembers(findings, at, sf, text, name, members.properties, MIN_ENUM_MEMBER_WORDS);
        if (isDefineToken(decl)) {
          const doc = docOf(sf, text, stmt);
          const problem = !doc
            ? "has no TSDoc block"
            : !(/resol/i.test(doc) && /provid/i.test(doc))
              ? "is a DI token whose TSDoc must say what resolves to it and who provides it"
              : summaryProblem(doc);
          if (problem) findings.push(`${at(stmt.getStart(sf))}: export const ${name} ${problem}`);
        } else {
          requireDoc(findings, at, sf, text, stmt, `export const ${name}`);
        }
      }
      continue;
    }
    if (
      ts.isFunctionDeclaration(stmt) ||
      ts.isClassDeclaration(stmt) ||
      ts.isInterfaceDeclaration(stmt) ||
      ts.isTypeAliasDeclaration(stmt) ||
      ts.isEnumDeclaration(stmt) ||
      ts.isModuleDeclaration(stmt)
    ) {
      const name = stmt.name?.getText(sf) ?? "default";
      requireDoc(findings, at, sf, text, stmt, `export ${name}`);
    }
    if (ts.isInterfaceDeclaration(stmt)) {
      requireMembers(findings, at, sf, text, stmt.name.text, signatureMembers(stmt.members));
    }
    if (ts.isEnumDeclaration(stmt)) {
      requireMembers(findings, at, sf, text, stmt.name.text, stmt.members, MIN_ENUM_MEMBER_WORDS);
    }
    if (ts.isTypeAliasDeclaration(stmt) && ts.isTypeLiteralNode(stmt.type)) {
      requireMembers(findings, at, sf, text, stmt.name.text, signatureMembers(stmt.type.members));
    }
    if (ts.isClassDeclaration(stmt)) {
      const publicMembers = stmt.members.filter(
        (m) =>
          (ts.isPropertyDeclaration(m) ||
            ts.isMethodDeclaration(m) ||
            ts.isGetAccessorDeclaration(m) ||
            ts.isSetAccessorDeclaration(m)) &&
          !isInternalMember(m),
      );
      requireMembers(findings, at, sf, text, stmt.name?.text ?? "default", publicMembers);
    }
  }
  return findings;
}
