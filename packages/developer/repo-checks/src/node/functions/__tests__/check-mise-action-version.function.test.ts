/**
 * Stackra file contract:
 * Purpose: unit tests of `checkMiseActionVersion`: steps that pin one version pass, in workflows and composite actions;
 *          a step without a version is one finding; two versions are one finding naming both; other actions, an
 *          unparsable file and an fflow-generated one are skipped.
 * Boundary: test only.
 * Runtime: node (vitest)
 * Governing contract: ADR 0027; ADR 0022 (test placement).
 */
import { describe, expect, it } from "@stackra/testing";

import { checkMiseActionVersion } from "#node/functions/check-mise-action-version.function";

/** A workflow whose one job runs mise-action with `with`. */
const workflow = (withBlock: string): string =>
  `jobs:\n  a:\n    steps:\n      - uses: actions/checkout@v4\n      - uses: jdx/mise-action@abc # v5\n${withBlock}`;

describe("checkMiseActionVersion", () => {
  it("passes steps that pin one version, in a workflow and a composite action", () => {
    const action =
      "runs:\n  using: composite\n  steps:\n    - uses: jdx/mise-action@abc\n      with:\n        version: 2026.11.4\n";
    expect(
      checkMiseActionVersion([
        [".github/workflows/ci.yml", workflow("        with:\n          version: 2026.11.4\n")],
        [".github/actions/x/action.yml", action],
      ]),
    ).toEqual([]);
  });

  it("reports a step with no version", () => {
    const findings = checkMiseActionVersion([
      [".github/workflows/ci.yml", workflow("        with:\n          install_args: node pnpm\n")],
    ]);
    expect(findings).toHaveLength(1);
    expect(findings[0]).toContain(".github/workflows/ci.yml");
  });

  it("reports two pinned versions once, naming both", () => {
    const findings = checkMiseActionVersion([
      [".github/workflows/a.yml", workflow("        with:\n          version: 2026.11.4\n")],
      [".github/workflows/b.yml", workflow("        with:\n          version: 2026.11.2\n")],
    ]);
    expect(findings).toHaveLength(1);
    expect(findings[0]).toContain("2026.11.4");
    expect(findings[0]).toContain("2026.11.2");
  });

  it("skips a workflow fflow sync generated, which Flow pins in its template", () => {
    const generated = `# Generated by fflow from the stackra preset 0.7.0: do not edit.\n${workflow("")}`;
    expect(checkMiseActionVersion([[".github/workflows/fflow-baseline.yml", generated]])).toEqual(
      [],
    );
  });

  it("skips other actions and a file that does not parse", () => {
    expect(
      checkMiseActionVersion([
        [".github/workflows/a.yml", "jobs:\n  a:\n    steps:\n      - uses: actions/checkout@v4\n"],
        [".github/workflows/b.yml", "jobs: [\n"],
      ]),
    ).toEqual([]);
  });
});
