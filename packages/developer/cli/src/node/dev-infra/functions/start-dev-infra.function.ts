/**
 * Stackra file contract:
 * Purpose: `startDevInfra(root, options, io, run)`, the dev compose step of `stackra dev`: plans the root runway's
 *          `environments.dev.infra` for the lane (`planDevInfra`), writes `.stackra/dev/compose.yaml` and
 *          `.stackra/dev/compose.shared.yaml`, then runs `docker compose -f <file> up --detach --wait` for each file
 *          that has a container to start (the shared one first), so every container is healthy before the member
 *          starts. It records the lane and opt-ins in `.stackra/dev/infra.json` for the members' runs, and prints each
 *          address and the command that stops them.
 * Boundary: a refusal prints every issue and returns 1 before any file is written; an image without a digest only
 *           warns. Nothing runs when no container is declared, so a workspace with only Encore's Postgres needs no
 *           Docker. The containers keep running after `stackra dev` stops (the next start is instant); volumes are never
 *           removed. `run` is the process runner (`runProcess`), a parameter so tests start no Docker. No value is
 *           written: the files hold images, ports and plain variables only.
 * Runtime: node
 * Governing contract: ADR 0199 (decision 3: `stackra dev` runs gen, `encore run` and a small compose file); ADR 0296
 *                     (decision 1: lanes); STA-2664 (item 6).
 */
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

import type { ComposeDocument } from "@stackra/runway";
import { stringify } from "yaml";

import { DEV_INFRA_FILES } from "#node/dev-infra/constants/dev-infra-files.constant";
import { planDevInfra } from "#node/dev-infra/functions/plan-dev-infra.function";
import { runProcess } from "#node/functions/run-process.function";
import type { CliIo } from "#node/types/cli-io.type";
import type { ToolRun } from "#node/types/tool-run.type";

/** The first lines of every generated Compose file. */
const HEADER =
  "# Generated by `stackra dev` from runway.yaml (environments.dev.infra); do not edit, change the runway.\n";

/** The exit code `runProcess` gives a program that cannot start. */
const CANNOT_START = 127;

/** One Compose file to bring up. */
type Up = { readonly file: string; readonly document: ComposeDocument; readonly lane: boolean };

/**
 * Starts the dev compose of the workspace at `root` and resolves with an exit code.
 *
 * @param root - the workspace root (the folder of the root `runway.yaml`).
 * @param options - the dev lane and the `when: opt-in` blocks to start too.
 * @param io - where the step and Docker write.
 * @param run - starts one process; `runProcess` outside tests.
 * @example
 * if ((await startDevInfra(root, { lane: 0, optIn: [] }, io)) !== 0) return 1;
 */
export async function startDevInfra(
  root: string,
  options: { readonly lane: number; readonly optIn: readonly string[] },
  io: CliIo,
  run: (tool: ToolRun, io: CliIo) => Promise<number> = runProcess,
): Promise<number> {
  const plan = planDevInfra(root, options.lane, options.optIn);
  const state = join(root, DEV_INFRA_FILES.state);
  if (plan === undefined) {
    rmSync(state, { force: true });
    return 0;
  }
  for (const issue of plan.issues)
    io.err(`stackra dev: environments.dev.infra ${issue.code}: ${issue.message}\n`);
  if (plan.issues.length > 0) return 1;
  for (const warning of plan.warnings) io.err(`stackra dev: ${warning}\n`);

  const ups: Up[] = [];
  for (const [path, document, lane] of [
    [DEV_INFRA_FILES.shared, plan.shared, false],
    [DEV_INFRA_FILES.lane, plan.lane, true],
  ] as const) {
    const file = join(root, path);
    if (document === undefined) {
      rmSync(file, { force: true });
      continue;
    }
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, `${HEADER}${stringify(document, { lineWidth: 0 })}`);
    ups.push({ file: path, document, lane });
  }
  mkdirSync(dirname(state), { recursive: true });
  writeFileSync(
    state,
    `${JSON.stringify({ lane: options.lane, optIn: options.optIn }, null, 2)}\n`,
  );

  const starting = plan.services.filter(
    (service) => !service.optIn || options.optIn.includes(service.name),
  );
  if (starting.length === 0) return 0;
  io.out(`dev infra: starting ${starting.map((service) => service.name).join(", ")}\n`);
  for (const { file, document, lane } of ups) {
    const names = Object.keys(document.services);
    if (!starting.some((service) => names.includes(service.name))) continue;
    const profiles = options.optIn
      .filter((name) => names.includes(name))
      .flatMap((name) => ["--profile", name]);
    // `--remove-orphans` only in the lane's own project: the shared one also holds other worktrees' containers.
    const code = await run(
      {
        command: "docker",
        args: [
          "compose",
          "-f",
          file,
          ...profiles,
          "up",
          "--detach",
          "--wait",
          ...(lane ? ["--remove-orphans"] : []),
        ],
        cwd: root,
      },
      io,
    );
    if (code !== 0) {
      io.err(
        code === CANNOT_START
          ? "stackra dev: the dev compose needs Docker with the compose plugin (`stackra doctor` checks it), or run `stackra dev --no-infra`\n"
          : `stackra dev: \`docker compose -f ${file} up\` failed (exit ${code}); \`docker compose -f ${file} logs\` shows why\n`,
      );
      return code;
    }
  }
  for (const service of starting) io.out(`  ${service.name}: ${service.url}\n`);
  io.out(
    `dev infra keeps running after stackra dev; stop it with ${ups.map(({ file }) => `\`docker compose -f ${file} down\``).join(" and ")}\n`,
  );
  return 0;
}
