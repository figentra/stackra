/**
 * Stackra file contract:
 * Purpose: unit tests of `startDevInfra`: nothing runs without a runway or with only Encore's own blocks; the shared
 *          and lane Compose files are written as planned and brought up shared first, the lane's with
 *          `--remove-orphans`; the state file records lane and opt-ins; an opt-in block starts only under its profile;
 *          a refusal stops before any file or Docker call; a missing Docker names the fix.
 * Boundary: test only; a temporary workspace and a fake process runner, so no Docker starts.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0199 (decision 3); STA-2664 (item 6).
 */
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "@stackra/testing";
import { parse } from "yaml";

import { startDevInfra } from "#node/dev-infra/functions/start-dev-infra.function";
import { captureIo } from "#node/functions/capture-io.function";
import type { ToolRun } from "#node/types/tool-run.type";

let root = "";

/** A digest-pinned image of `name`. */
const pinned = (name: string): string => `"${name}@sha256:${"a".repeat(64)}"`;

/** Writes a root runway whose dev infra holds `infra` (YAML lines under `infra:`). */
function runway(...infra: string[]): void {
  writeFileSync(
    join(root, "runway.yaml"),
    [
      "version: 3",
      "project: acme",
      "environments:",
      "  dev:",
      "    lanes: { portStep: 100 }",
      "    infra:",
      "      gateway: { port: 4000, dashboard: 9400 }",
      ...infra.map((line) => `      ${line}`),
      "",
    ].join("\n"),
  );
}

/** A fake runner that records each call and answers `code`. */
function runner(code = 0): { calls: ToolRun[]; run: (tool: ToolRun) => Promise<number> } {
  const calls: ToolRun[] = [];
  return {
    calls,
    run: (tool) => {
      calls.push(tool);
      return Promise.resolve(code);
    },
  };
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), "stackra-dev-infra-"));
});

afterEach(() => {
  rmSync(root, { recursive: true, force: true });
});

describe("startDevInfra", () => {
  it("runs nothing in a workspace without a runway", async () => {
    const { calls, run } = runner();
    const { io } = captureIo();
    expect(await startDevInfra(root, { lane: 0, optIn: [] }, io, run)).toBe(0);
    expect(calls).toEqual([]);
    expect(existsSync(join(root, ".stackra"))).toBe(false);
  });

  it("runs no Docker when only Encore's own gateway and Postgres are declared", async () => {
    runway("postgres: { image: postgres:17, port: 5432 }");
    const { calls, run } = runner();
    const { io } = captureIo();
    expect(await startDevInfra(root, { lane: 0, optIn: [] }, io, run)).toBe(0);
    expect(calls).toEqual([]);
    expect(existsSync(join(root, ".stackra/dev/compose.yaml"))).toBe(false);
  });

  it("writes both Compose files and brings the shared one up first, then the lane's", async () => {
    runway(
      `valkey: { image: ${pinned("valkey/valkey:8.1")}, port: 6379 }`,
      `clamav: { image: ${pinned("clamav/clamav:1.5.3")}, port: 3310 }`,
    );
    const { calls, run } = runner();
    const { io, output } = captureIo();
    expect(await startDevInfra(root, { lane: 1, optIn: [] }, io, run)).toBe(0);

    const lane = parse(readFileSync(join(root, ".stackra/dev/compose.yaml"), "utf8")) as {
      name: string;
      services: Record<string, { ports: string[] }>;
    };
    expect(lane.name).toBe("acme-dev-lane-1");
    expect(lane.services["valkey"]?.ports).toEqual(["127.0.0.1:6479:6379"]);
    const shared = parse(readFileSync(join(root, ".stackra/dev/compose.shared.yaml"), "utf8")) as {
      name: string;
      services: Record<string, { ports: string[] }>;
    };
    expect(shared.name).toBe("acme-dev-shared");
    expect(shared.services["clamav"]?.ports).toEqual(["127.0.0.1:3310:3310"]);
    expect(readFileSync(join(root, ".stackra/dev/compose.yaml"), "utf8")).toMatch(
      /^# Generated by `stackra dev`/,
    );

    expect(calls.map(({ command, args, cwd }) => [command, args, cwd])).toEqual([
      [
        "docker",
        ["compose", "-f", ".stackra/dev/compose.shared.yaml", "up", "--detach", "--wait"],
        root,
      ],
      [
        "docker",
        [
          "compose",
          "-f",
          ".stackra/dev/compose.yaml",
          "up",
          "--detach",
          "--wait",
          "--remove-orphans",
        ],
        root,
      ],
    ]);
    expect(JSON.parse(readFileSync(join(root, ".stackra/dev/infra.json"), "utf8"))).toEqual({
      lane: 1,
      optIn: [],
    });
    expect(output()).toContain("valkey: redis://127.0.0.1:6479");
    expect(output()).toContain("clamav: tcp://127.0.0.1:3310");
    expect(output()).toContain("docker compose -f .stackra/dev/compose.yaml down");
  });

  it("starts an opt-in block only when asked, under its own profile", async () => {
    runway(
      `"otel-lgtm": { image: ${pinned("grafana/otel-lgtm:0.37.0")}, grpcPort: 4317, httpPort: 4318, uiPort: 3000, when: opt-in }`,
    );
    const quiet = runner();
    expect(await startDevInfra(root, { lane: 0, optIn: [] }, captureIo().io, quiet.run)).toBe(0);
    expect(quiet.calls).toEqual([]);
    expect(existsSync(join(root, ".stackra/dev/compose.yaml"))).toBe(true);

    const asked = runner();
    expect(
      await startDevInfra(root, { lane: 0, optIn: ["otel-lgtm"] }, captureIo().io, asked.run),
    ).toBe(0);
    expect(asked.calls[0]?.args).toEqual([
      "compose",
      "-f",
      ".stackra/dev/compose.yaml",
      "--profile",
      "otel-lgtm",
      "up",
      "--detach",
      "--wait",
      "--remove-orphans",
    ]);
  });

  it("prints every refusal and stops before any file or Docker call", async () => {
    runway("valkey: { image: valkey/valkey:8.1 }", "thing: { image: example/thing:1 }");
    const { calls, run } = runner();
    const { io, output } = captureIo();
    expect(await startDevInfra(root, { lane: 0, optIn: [] }, io, run)).toBe(1);
    expect(calls).toEqual([]);
    expect(output()).toContain("infra_port_missing: valkey.port");
    expect(output()).toContain("infra_kind_unknown: thing");
    expect(existsSync(join(root, ".stackra/dev/compose.yaml"))).toBe(false);
  });

  it("names Docker as the fix when it cannot start, and returns its code", async () => {
    runway(`valkey: { image: ${pinned("valkey/valkey:8.1")}, port: 6379 }`);
    const { run } = runner(127);
    const { io, output } = captureIo();
    expect(await startDevInfra(root, { lane: 0, optIn: [] }, io, run)).toBe(127);
    expect(output()).toContain("needs Docker with the compose plugin");
    expect(output()).toContain("--no-infra");
  });

  it("removes a Compose file the runway no longer needs", async () => {
    runway(`valkey: { image: ${pinned("valkey/valkey:8.1")}, port: 6379 }`);
    await startDevInfra(root, { lane: 0, optIn: [] }, captureIo().io, runner().run);
    runway();
    await startDevInfra(root, { lane: 0, optIn: [] }, captureIo().io, runner().run);
    expect(existsSync(join(root, ".stackra/dev/compose.yaml"))).toBe(false);
  });
});
