/**
 * Stackra file contract:
 * Purpose: unit tests of `emitMigrations`: one `.up.sql` per step with a dense global sequence, `_<n>` step suffixes,
 *          the `-- stackra:transactional=false` header first on an online step, and a `.down.sql` only for a step
 *          with an inverse.
 * Boundary: test only; units are built inline.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0159 (decision 2 as amended 2026-10-24).
 */
import { describe, expect, it } from "@stackra/testing";

import { emitMigrations } from "#core/functions/emit-migrations.function";
import type { MigrationUnit } from "#core/types/migration-unit.type";

const CREATE: MigrationUnit = {
  id: "billing.0001_create_invoices",
  owner: "member",
  file: "src/modules/billing/database/migrations/0001-create-invoices.migration.ts",
  after: [],
  steps: [
    { sql: ["create table a (id int)"], transactional: true, inverse: ["drop table a"] },
    { sql: ["create index concurrently i on a (id)"], transactional: false, inverse: false },
  ],
};

const SEARCH: MigrationUnit = {
  id: "search.0001_create_text_functions",
  owner: "package",
  file: "@stackra/search/src/node/database/migrations/0001-create-text-functions.migration.ts",
  after: [],
  steps: [{ sql: ["select 1"], transactional: true, inverse: ["select 2"] }],
};

describe("emitMigrations", () => {
  const files = emitMigrations([SEARCH, CREATE]);

  it("numbers every step once, in order, with step suffixes for a multi-step migration", () => {
    expect(files.map((file) => file.path)).toEqual([
      ".stackra/migrations/0001_search_0001_create_text_functions.up.sql",
      ".stackra/migrations/0001_search_0001_create_text_functions.down.sql",
      ".stackra/migrations/0002_billing_0001_create_invoices_1.up.sql",
      ".stackra/migrations/0002_billing_0001_create_invoices_1.down.sql",
      ".stackra/migrations/0003_billing_0001_create_invoices_2.up.sql",
    ]);
  });

  it("opens an online step with the non-transactional header and ends each statement", () => {
    const online = files.find((file) =>
      file.path.endsWith("0003_billing_0001_create_invoices_2.up.sql"),
    );
    expect(online?.content.startsWith("-- stackra:transactional=false\n")).toBe(true);
    expect(online?.content.endsWith("create index concurrently i on a (id);\n")).toBe(true);
  });

  it("keeps a transactional step free of the header", () => {
    expect(files[0]?.content.startsWith("-- generated by stackra gen")).toBe(true);
  });
});
