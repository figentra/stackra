/**
 * Stackra file contract:
 * Purpose: unit tests of `emitE2ePageFiles`: the four files under `.stackra/`, the page glob and the path-to-page
 *          rule, the right-to-left languages, the console error of an unknown page, and the two configs that name
 *          `@stackra/testing/e2e`.
 * Boundary: test only; pure.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement; package e2e); ADR 0295 (decision 5).
 */
import { describe, expect, it } from "@stackra/testing";

import { emitE2ePageFiles } from "#core/functions/emit-e2e-page-files.function";

const files = emitE2ePageFiles("@acme/widget");
const content = (path: string): string => files.find((file) => file.path === path)?.content ?? "";

describe("emitE2ePageFiles", () => {
  it("writes the Vite app and the Playwright config under .stackra/", () => {
    expect(files.map((file) => file.path)).toEqual([
      ".stackra/e2e/index.html",
      ".stackra/e2e/main.tsx",
      ".stackra/e2e/vite.config.ts",
      ".stackra/playwright.e2e.config.ts",
    ]);
  });

  it("mounts the page in a root element with a module script", () => {
    const html = content(".stackra/e2e/index.html");
    expect(html).toContain('<div id="root"></div>');
    expect(html).toContain('<script type="module" src="./main.tsx"></script>');
  });

  it("renders the page named by the URL path and logs an unknown one", () => {
    const main = content(".stackra/e2e/main.tsx");
    expect(main).toContain('import.meta.glob("../../src/**/__tests__/*.e2e.page.tsx")');
    expect(main).toContain("location.pathname.slice(1)");
    expect(main).toContain("createRoot(container)");
    expect(main).toContain("createElement(module.default)");
    expect(main).toContain("console.error(`no e2e page ${name}`)");
  });

  it("sets the document language and direction before rendering", () => {
    const main = content(".stackra/e2e/main.tsx");
    expect(main).toContain("/^(ar|he|fa|ur)/i");
    expect(main).toContain("document.documentElement.lang = language;");
    expect(main).toContain('? "rtl" : "ltr"');
    expect(main.indexOf("documentElement.dir")).toBeLessThan(main.indexOf("root.render"));
  });

  it("builds both configs with @stackra/testing/e2e from the member root", () => {
    const vite = content(".stackra/e2e/vite.config.ts");
    expect(vite).toContain('import { packageE2eVite } from "@stackra/testing/e2e";');
    expect(vite).toContain('new URL("../..", import.meta.url)');
    const playwright = content(".stackra/playwright.e2e.config.ts");
    expect(playwright).toContain('import { packageE2ePreset } from "@stackra/testing/e2e";');
    expect(playwright).toContain('new URL("..", import.meta.url)');
    expect(playwright).toContain('package: "@acme/widget",');
  });

  it("opens each generated file with the generated notice", () => {
    for (const file of files) expect(file.content).toContain("generated by stackra gen");
  });
});
