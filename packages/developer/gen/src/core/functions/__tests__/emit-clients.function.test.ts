/**
 * Stackra file contract:
 * Purpose: unit tests of `emitClients`: one `.stackra/gen/clients/<service>.ts` per consumed service, written from the
 *          producer's manifest (enums, shapes in dependency order, refusals, integration events, call descriptors named
 *          after the producer's classes, and the `<Service>Client` with members grouped by model); the refusals for
 *          a service without a manifest and a client imported under another name; a service consumed only by a
 *          listener of its event, and the refusal of an event it does not publish; and `generateMember` writing the
 *          file and binding the client with its `ClientTransport`.
 * Boundary: test only; the producer is the commerce IR fixture's manifest, the consumer a one-class service IR.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0260 (decisions 2 to 6); ADR 0263 (a class is its own token).
 */
import { describe, expect, it } from "@stackra/testing";

import { buildManifest } from "#core/functions/build-manifest.function";
import { emitClients } from "#core/functions/emit-clients.function";
import { generateMember } from "#core/functions/generate-member.function";
import type { DeclaredClass } from "#core/types/declared-class.type";
import type { MemberIR } from "#core/types/member-ir.type";
import { COMMERCE_IR } from "#core/__tests__/fixtures/commerce-ir.fixture";

const PRODUCER = buildManifest(COMMERCE_IR).manifest;

/** A service class that injects `client` from `#stackra/clients/<service>`. */
function consumerClass(client: string, service: string): DeclaredClass {
  return {
    name: "StorefrontService",
    kind: "service",
    module: "storefront",
    file: "src/modules/storefront/services/storefront.service.ts",
    importPath: "#modules/storefront/services/storefront.service",
    options: {},
    deps: [{ class: { name: client, from: `#stackra/clients/${service}` } }],
    facets: [],
    methods: [],
    refusals: [],
    statics: {},
    traits: [],
  };
}

/** The channels service, consuming the commerce service's client. */
function consumer(overrides: Partial<MemberIR> = {}): MemberIR {
  return {
    member: "channels",
    package: "@acme/service-channels",
    version: "0.1.0",
    layout: "service",
    modules: ["storefront"],
    classes: [consumerClass("CommerceClient", "commerce")],
    shapes: [],
    enums: [],
    files: [],
    dependencies: [],
    errors: [],
    services: [{ member: "commerce", manifest: PRODUCER }],
    ...overrides,
  };
}

describe("emitClients", () => {
  const { files, errors } = emitClients(consumer());
  const content = files[0]?.content ?? "";

  it("writes one client file per consumed service", () => {
    expect(errors).toEqual([]);
    expect(files.map((file) => file.path)).toEqual([".stackra/gen/clients/commerce.ts"]);
    expect(content).toContain("generated by stackra gen — do not edit");
  });

  it("writes the client class with one member per call, grouped by model", () => {
    expect(content).toContain("export class CommerceClient extends ServiceClient {");
    expect(content).toContain("  readonly order = {");
    expect(content).toContain("    cancel: this.member(CancelOrderAction),");
    expect(content).toContain("    list: this.member(ListOrdersQuery),");
  });

  it("names each descriptor after the producer's class, with its key and route", () => {
    expect(content).toContain(
      'export const CancelOrderAction = remoteAction("orders.order.cancel@1", { input: CancelOrderInput, ' +
        'output: CancelOrderOutput, endpoint: { method: HttpMethod.Put, path: "/orders/:orderId/cancel" } });',
    );
    expect(content).toContain('export const ListOrdersQuery = remoteQuery("orders.order.list@1",');
  });

  it("writes shapes, enums, refusals and integration events from the manifest", () => {
    expect(content).toContain(
      'export class CancelOrderInput extends remoteShape("orders.CancelOrderInput", CancelOrderInput$) {}',
    );
    expect(content).toContain('publicId("ord")');
    expect(content).toContain("export const OrderStatus = Enum.of({");
    expect(content).toContain(
      'export class OrderNotCancellableError extends remoteRefusal("orders", "order_not_cancellable", { kind: ErrorKind.FailedPrecondition }) {}',
    );
    expect(content).toContain('export class OrderPaid extends remoteEvent("orders.order.paid.v1",');
    expect(content.indexOf("const OrderView$")).toBeLessThan(
      content.indexOf("const ListOrdersOutput$"),
    );
  });

  it("refuses a service with no committed manifest", () => {
    const refused = emitClients(consumer({ services: [] }));
    expect(refused.files).toEqual([]);
    expect(refused.errors.map((error) => error.code)).toEqual(["client_service_unknown"]);
  });

  it("refuses a client imported under another name", () => {
    const refused = emitClients(consumer({ classes: [consumerClass("ShopClient", "commerce")] }));
    expect(refused.errors.map((error) => error.code)).toEqual(["client_name_mismatch"]);
  });

  it("writes nothing for a member that injects no client", () => {
    expect(emitClients(COMMERCE_IR)).toEqual({ files: [], errors: [] });
  });
});

/** A listener of the commerce service's `event`, imported from `#stackra/clients/commerce`. */
function listenerOf(event: string): DeclaredClass {
  return {
    ...consumerClass("CommerceClient", "commerce"),
    name: "SyncOnOrderPaidListener",
    kind: "listener",
    file: "src/modules/storefront/listeners/sync-on-order-paid.listener.ts",
    importPath: "#modules/storefront/listeners/sync-on-order-paid.listener",
    deps: [],
    handle: { event: { name: event, from: "#stackra/clients/commerce" } },
  };
}

describe("emitClients for a listener of another service's event", () => {
  it("writes the client file of a service consumed only by a listener", () => {
    const { files, errors } = emitClients(consumer({ classes: [listenerOf("OrderPaid")] }));
    expect(errors).toEqual([]);
    expect(files.map((file) => file.path)).toEqual([".stackra/gen/clients/commerce.ts"]);
    expect(files[0]?.content).toContain(
      'export class OrderPaid extends remoteEvent("orders.order.paid.v1",',
    );
  });

  it("refuses an event the producer does not publish, so there is no wire-name fallback", () => {
    const refused = emitClients(consumer({ classes: [listenerOf("OrderVanished")] }));
    expect(refused.files).toEqual([]);
    expect(refused.errors.map((error) => [error.code, error.subject])).toEqual([
      ["client_event_unknown", "SyncOnOrderPaidListener.handle"],
    ]);
  });

  it("refuses a listened-to service with no committed manifest", () => {
    const refused = emitClients(consumer({ classes: [listenerOf("OrderPaid")], services: [] }));
    expect(refused.errors.map((error) => error.code)).toEqual(["client_service_unknown"]);
  });
});

describe("generateMember with a consumed client", () => {
  it("writes the client and binds it as a class token over ClientTransport", () => {
    const { files, errors } = generateMember(consumer());
    expect(errors).toEqual([]);
    expect(files.some((file) => file.path === ".stackra/gen/clients/commerce.ts")).toBe(true);
    const wiring = files.find((file) => file.path === ".stackra/gen/wiring.ts")?.content ?? "";
    expect(wiring).toContain('import { CommerceClient } from "#stackra/clients/commerce";');
    expect(wiring).toContain(
      '    { module: "storefront", kind: "service", provide: CommerceClient, deps: [ClientTransport] },',
    );
  });
});
