/**
 * Stackra file contract:
 * Purpose: `provenanceComment`, the HTML comment every rendered Markdown file carries: who generated it, from which
 *          document, and that the source is what gets edited. It names the document, never its path, so the bytes do
 *          not depend on the machine that rendered them.
 * Boundary: internal; pure.
 * Runtime: isomorphic
 * Governing contract: ADR 0282 (decision 2: written once, rendered into every layout).
 */

/**
 * The comment line.
 *
 * @param generator - who generated the file.
 * @param subject - what it was generated from (`skill "naming"`, `3 rules`).
 * @example
 * provenanceComment("stackra agents setup", 'skill "naming"');
 * // '<!-- generated by stackra agents setup from skill "naming"; edit the source, not this file -->'
 */
export function provenanceComment(generator: string, subject: string): string {
  return `<!-- generated by ${generator} from ${subject}; edit the source, not this file -->`;
}
