/**
 * Stackra file contract:
 * Purpose: unit tests of `renderAssistant`: it dispatches to every assistant, sorts files by path, defaults the
 *          generator, renders the same bytes twice, freezes its result, and refuses an unknown assistant and two
 *          documents on one path.
 * Boundary: test only; documents are built inline in the shapes `@stackra/skills` parses.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0282 (decisions 2 and 10); ADR 0286 (decision 6).
 */
import { Enum } from "@stackra/contracts";
import type { AgentDocument, RuleDocument, SkillDocument, SubagentDocument } from "@stackra/skills";
import { describe, expect, it } from "@stackra/testing";

import { Assistant } from "#core/enums/assistant.enum";
import { RenderInputError } from "#core/errors/render-input.error";
import { renderAssistant } from "#core/functions/render-assistant.function";

const skill: SkillDocument = {
  kind: "skill",
  name: "naming",
  description: "Name things",
  body: "# Naming\n",
  source: "a",
};
const rule: RuleDocument = {
  kind: "rule",
  name: "versions",
  title: "Versions",
  description: "Pin versions",
  always: true,
  globs: [],
  body: "# Versions\n",
  source: "b",
};
const subagent: SubagentDocument = {
  kind: "subagent",
  name: "reviewer",
  description: "Reviews diffs",
  tools: ["Read"],
  body: "Review.\n",
  source: "c",
};
const documents: readonly AgentDocument[] = [skill, rule, subagent];

describe("renderAssistant", () => {
  it("renders every assistant's layout", () => {
    const paths = Object.fromEntries(
      Enum.values(Assistant).map((assistant) => [
        assistant,
        renderAssistant(assistant, documents).files.map((file) => file.path),
      ]),
    );
    expect(paths).toEqual({
      claude_code: ["agents/reviewer.md", "rules/versions.md", "skills/naming/SKILL.md"],
      opencode: ["agents/reviewer.md", "skills/naming/SKILL.md"],
      kiro: ["agents/reviewer.md", "skills/naming/SKILL.md", "steering/versions.md"],
      cursor: ["rules/naming.mdc", "rules/versions.mdc"],
      agents_md: ["AGENTS.md"],
    });
  });

  it("names @stackra/renderers as the generator by default, or the one given", () => {
    expect(renderAssistant(Assistant.ClaudeCode, [skill]).files[0]?.content).toContain(
      "generated by @stackra/renderers",
    );
    expect(
      renderAssistant(Assistant.ClaudeCode, [skill], { generator: "vellum" }).files[0]?.content,
    ).toContain("generated by vellum");
  });

  it("renders the same bytes for the same documents in any order", () => {
    const first = renderAssistant(Assistant.Kiro, documents);
    expect(renderAssistant(Assistant.Kiro, [...documents].reverse()).files).toEqual(first.files);
  });

  it("returns frozen lists, with the skipped documents", () => {
    const result = renderAssistant(Assistant.Cursor, documents);
    expect(Object.isFrozen(result.files)).toBe(true);
    expect(Object.isFrozen(result.skipped)).toBe(true);
    expect(result.skipped).toEqual([
      { kind: "subagent", name: "reviewer", reason: "Cursor has no sub-agent file" },
    ]);
  });

  it("refuses two documents that write one path", () => {
    const onRequest: RuleDocument = { ...rule, name: "naming", always: false };
    expect(() => renderAssistant(Assistant.ClaudeCode, [skill, onRequest])).toThrow(
      RenderInputError,
    );
    expect(() => renderAssistant(Assistant.ClaudeCode, [skill, onRequest])).toThrow(
      /skills\/naming\/SKILL\.md/,
    );
  });

  it("refuses an unknown assistant", () => {
    expect(() => renderAssistant("vim" as Assistant, documents)).toThrow(
      "Cannot render for vim: unknown assistant",
    );
  });
});
