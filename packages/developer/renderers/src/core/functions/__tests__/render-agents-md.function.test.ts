/**
 * Stackra file contract:
 * Purpose: unit tests of `renderAgentsMd`: always-on rules then scoped rules under their globs, headings demoted two
 *          levels, every other document skipped, and no file without a rule for it.
 * Boundary: test only; documents are built inline in the shapes `@stackra/skills` parses.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0282 (decision 2).
 */
import type { RuleDocument, SkillDocument } from "@stackra/skills";
import { describe, expect, it } from "@stackra/testing";

import { renderAgentsMd } from "#core/functions/render-agents-md.function";

const rule = (overrides: Partial<RuleDocument>): RuleDocument => ({
  kind: "rule",
  name: "versions",
  title: "Versions",
  description: "Pin versions",
  always: false,
  globs: [],
  body: "# Versions\n\nCatalogs only.\n",
  source: "a",
  ...overrides,
});
const skill: SkillDocument = {
  kind: "skill",
  name: "naming",
  description: "Name things",
  body: "# Naming\n",
  source: "b",
};

describe("renderAgentsMd", () => {
  it("writes always-on rules, then scoped rules under their globs", () => {
    const { files, skipped } = renderAgentsMd(
      [
        rule({
          name: "services",
          globs: ["services/**", "*.ts"],
          body: "# Services\n\n## Checklist\n",
        }),
        rule({ always: true }),
      ],
      "gen",
    );
    expect(skipped).toEqual([]);
    expect(files).toEqual([
      {
        path: "AGENTS.md",
        content:
          [
            "<!-- generated by gen from 2 rules; edit the source, not this file -->",
            "# Rules",
            "## Always",
            "### Versions\n\nCatalogs only.",
            "## When touching matching files",
            "When touching `services/**`, `*.ts`:\n\n### Services\n\n#### Checklist",
          ].join("\n\n") + "\n",
      },
    ]);
  });

  it("leaves out a section with no rule", () => {
    const { files } = renderAgentsMd([rule({ always: true })], "gen");
    expect(files[0]?.content).toContain("from 1 rule;");
    expect(files[0]?.content).not.toContain("## When touching matching files");
  });

  it("skips skills, rules read on request and every other kind, and writes no file without a rule for it", () => {
    const { files, skipped } = renderAgentsMd([skill, rule({ name: "tenancy" })], "gen");
    expect(files).toEqual([]);
    expect(skipped.map((entry) => [entry.kind, entry.name])).toEqual([
      ["skill", "naming"],
      ["rule", "tenancy"],
    ]);
  });
});
