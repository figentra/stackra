/**
 * Stackra file contract:
 * Purpose: unit tests of `renderClaudeCode`: one file per skill, sub-agent, command and rule in Claude Code's layout, a
 *          rule read on request as a skill, and every hook in one `hooks/hooks.json` grouped by Claude Code event.
 * Boundary: test only; documents are built inline in the shapes `@stackra/skills` parses.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0282 (decisions 2 and 9).
 */
import type {
  CommandDocument,
  HookDocument,
  RuleDocument,
  SkillDocument,
  SubagentDocument,
} from "@stackra/skills";
import { describe, expect, it } from "@stackra/testing";
import { parse } from "yaml";

import { renderClaudeCode } from "#core/functions/render-claude-code.function";

const skill: SkillDocument = {
  kind: "skill",
  name: "naming",
  description: "Name things",
  body: "# Naming\n",
  source: "skills/naming/SKILL.md",
};
const rule = (overrides: Partial<RuleDocument>): RuleDocument => ({
  kind: "rule",
  name: "versions",
  title: "Versions",
  description: "Pin versions",
  always: false,
  globs: [],
  body: "# Versions\n",
  source: "rules/versions.md",
  ...overrides,
});
const subagent: SubagentDocument = {
  kind: "subagent",
  name: "reviewer",
  description: "Reviews diffs",
  tools: ["Read", "Grep"],
  body: "Review.\n",
  source: "subagents/reviewer.md",
};
const command: CommandDocument = {
  kind: "command",
  name: "ship",
  description: "Ship it",
  argumentHint: "<issue-key>",
  body: "Ship $ARGUMENTS\n",
  source: "commands/ship.md",
};
const hook = (name: string, event: HookDocument["event"], matcher?: string): HookDocument => ({
  kind: "hook",
  name,
  description: name,
  event,
  ...(matcher === undefined ? {} : { matcher }),
  run: `node ${name}.mjs`,
  body: "",
  source: `hooks/${name}.md`,
});

/** The parsed frontmatter of a rendered file. */
const frontMatterOf = (content: string): unknown => parse(content.split("---\n")[1] ?? "");

describe("renderClaudeCode", () => {
  it("writes a skill as SKILL.md with the Agent Skills frontmatter", () => {
    const { files, skipped } = renderClaudeCode([skill], "gen");
    expect(skipped).toEqual([]);
    expect(files).toEqual([
      {
        path: "skills/naming/SKILL.md",
        content:
          '---\nname: naming\ndescription: Name things\n---\n\n<!-- generated by gen from skill "naming"; edit the source, not this file -->\n\n# Naming\n',
      },
    ]);
  });

  it("writes an always-on rule with no frontmatter and a scoped rule with paths", () => {
    const { files } = renderClaudeCode(
      [rule({ always: true }), rule({ name: "services", globs: ["services/**", "src/**/*.ts"] })],
      "gen",
    );
    expect(files[0]?.path).toBe("rules/versions.md");
    expect(files[0]?.content.startsWith("<!-- generated by gen from rule")).toBe(true);
    expect(files[1]?.path).toBe("rules/services.md");
    expect(frontMatterOf(files[1]?.content ?? "")).toEqual({
      paths: ["services/**", "src/**/*.ts"],
    });
  });

  it("writes a rule read on request as a skill", () => {
    const { files } = renderClaudeCode([rule({ name: "tenancy" })], "gen");
    expect(files[0]?.path).toBe("skills/tenancy/SKILL.md");
    expect(frontMatterOf(files[0]?.content ?? "")).toEqual({
      name: "tenancy",
      description: "Pin versions",
    });
  });

  it("writes a sub-agent with its tools comma-separated, and none when the list is empty", () => {
    const { files } = renderClaudeCode(
      [subagent, { ...subagent, name: "helper", tools: [] }],
      "gen",
    );
    expect(files[0]?.path).toBe("agents/reviewer.md");
    expect(frontMatterOf(files[0]?.content ?? "")).toEqual({
      name: "reviewer",
      description: "Reviews diffs",
      tools: "Read, Grep",
    });
    expect(frontMatterOf(files[1]?.content ?? "")).toEqual({
      name: "helper",
      description: "Reviews diffs",
    });
  });

  it("writes a command with its argument hint", () => {
    const { files } = renderClaudeCode([command], "gen");
    expect(files[0]?.path).toBe("commands/ship.md");
    expect(frontMatterOf(files[0]?.content ?? "")).toEqual({
      description: "Ship it",
      "argument-hint": "<issue-key>",
    });
    expect(files[0]?.content.endsWith("Ship $ARGUMENTS\n")).toBe(true);
  });

  it("groups every hook into one hooks.json by Claude Code event", () => {
    const { files } = renderClaudeCode(
      [
        hook("audit", "post_tool_use"),
        hook("guard-bash", "pre_tool_use", "Bash"),
        hook("context", "session_start"),
      ],
      "gen",
    );
    expect(files).toHaveLength(1);
    expect(files[0]?.path).toBe("hooks/hooks.json");
    expect(JSON.parse(files[0]?.content ?? "")).toEqual({
      hooks: {
        SessionStart: [{ hooks: [{ type: "command", command: "node context.mjs" }] }],
        PreToolUse: [
          { matcher: "Bash", hooks: [{ type: "command", command: "node guard-bash.mjs" }] },
        ],
        PostToolUse: [{ hooks: [{ type: "command", command: "node audit.mjs" }] }],
      },
    });
    expect(Object.keys(JSON.parse(files[0]?.content ?? "").hooks)).toEqual([
      "SessionStart",
      "PreToolUse",
      "PostToolUse",
    ]);
  });

  it("writes no hooks.json when there is no hook", () => {
    expect(renderClaudeCode([skill], "gen").files.map((file) => file.path)).not.toContain(
      "hooks/hooks.json",
    );
  });
});
