/**
 * Stackra file contract:
 * Purpose: unit tests of `renderCursor`: `.mdc` rules with Cursor's three keys, skills as agent-requested rules,
 *          commands as plain Markdown, and sub-agents and hooks skipped.
 * Boundary: test only; documents are built inline in the shapes `@stackra/skills` parses.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022 (test placement); ADR 0282 (decision 2); ADR 0286 (decision 16).
 */
import type {
  CommandDocument,
  HookDocument,
  RuleDocument,
  SkillDocument,
  SubagentDocument,
} from "@stackra/skills";
import { describe, expect, it } from "@stackra/testing";

import { renderCursor } from "#core/functions/render-cursor.function";

const rule = (overrides: Partial<RuleDocument>): RuleDocument => ({
  kind: "rule",
  name: "versions",
  title: "Versions",
  description: "Pin versions: catalogs only",
  always: false,
  globs: [],
  body: "# Versions\n",
  source: "a",
  ...overrides,
});
const skill: SkillDocument = {
  kind: "skill",
  name: "naming",
  description: "Name things",
  body: "# Naming\n",
  source: "b",
};
const command: CommandDocument = {
  kind: "command",
  name: "ship",
  description: "Ship it",
  body: "Ship\n",
  source: "c",
};
const subagent: SubagentDocument = {
  kind: "subagent",
  name: "reviewer",
  description: "Reviews",
  tools: [],
  body: "",
  source: "d",
};
const hook: HookDocument = {
  kind: "hook",
  name: "guard",
  description: "Guard",
  event: "pre_tool_use",
  run: "node guard.mjs",
  body: "",
  source: "e",
};

describe("renderCursor", () => {
  it("writes an always-on rule with alwaysApply true and empty globs", () => {
    const { files } = renderCursor([rule({ always: true })], "gen");
    expect(files).toEqual([
      {
        path: "rules/versions.mdc",
        content:
          '---\ndescription: "Pin versions: catalogs only"\nglobs:\nalwaysApply: true\n---\n\n<!-- generated by gen from rule "versions"; edit the source, not this file -->\n\n# Versions\n',
      },
    ]);
  });

  it("writes a scoped rule's globs comma-separated and unquoted", () => {
    const { files } = renderCursor([rule({ globs: ["**/*.ts", "services/**"] })], "gen");
    expect(files[0]?.content).toContain("\nglobs: **/*.ts,services/**\nalwaysApply: false\n");
  });

  it("writes a skill as an agent-requested rule", () => {
    const { files } = renderCursor([skill], "gen");
    expect(files[0]?.path).toBe("rules/naming.mdc");
    expect(
      files[0]?.content.startsWith(
        '---\ndescription: "Name things"\nglobs:\nalwaysApply: false\n---\n',
      ),
    ).toBe(true);
  });

  it("writes a command as plain Markdown", () => {
    const { files } = renderCursor([command], "gen");
    expect(files).toEqual([
      {
        path: "commands/ship.md",
        content:
          '<!-- generated by gen from command "ship"; edit the source, not this file -->\n\nShip\n',
      },
    ]);
  });

  it("skips sub-agents and hooks", () => {
    const { files, skipped } = renderCursor([subagent, hook], "gen");
    expect(files).toEqual([]);
    expect(skipped.map((entry) => entry.kind)).toEqual(["subagent", "hook"]);
  });
});
