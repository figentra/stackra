/**
 * Stackra file contract:
 * Purpose: proves the ChatSurface draws each turn by its role, gives answers their reasoning, sources and actions,
 *          offers starters only while empty, sends a starter's prompt, passes the streaming state to the composer, draws
 *          a turn's AI SDK parts in their place, answers a tool approval and hands its handlers to the default part
 *          renderers.
 * Boundary: unit tier, jsdom, the real @stackra/ui components, except ChatMessage, PromptInput, Reasoning and Sources,
 *           which are DOM stand-ins shaped by their feat/c6-gap-ui contracts until that branch lands in this one.
 * Runtime: node (vitest)
 * Governing contract: ADR 0022; ADR 0269; ADR 0504.
 */
// @vitest-environment jsdom
import { afterEach, describe, expect, it } from "@stackra/testing";
import { cleanup, fireEvent, render, screen } from "@testing-library/react";
import type { ReactNode } from "react";
import { vi } from "vitest";

import { ChatSurface } from "#react/chat-surface/chat-surface";

vi.mock("@stackra/ui/react", async (importOriginal) => {
  const actual = await importOriginal<Record<string, unknown>>();
  const { createElement } = await import("react");
  return {
    ...actual,
    ChatMessage: (props: {
      readonly from: string;
      readonly authorLabel?: string;
      readonly children?: ReactNode;
      readonly actions?: ReactNode;
    }) =>
      createElement(
        "article",
        { "aria-label": props.authorLabel, "data-from": props.from },
        props.children,
        props.actions,
      ),
    PromptInput: (props: {
      readonly status?: string;
      readonly onSubmit: (value: string) => void;
    }) =>
      createElement(
        "button",
        { type: "button", "data-status": props.status, onClick: () => props.onSubmit("Hi") },
        "composer",
      ),
    Reasoning: (props: { readonly summary?: string }) =>
      createElement("details", null, props.summary),
    Sources: (props: {
      readonly sources: readonly { readonly key: string; readonly title?: string }[];
    }) =>
      createElement(
        "ol",
        null,
        ...props.sources.map((source) => createElement("li", { key: source.key }, source.title)),
      ),
  };
});

const LABELS = {
  log: "Conversation",
  generated: "Generated by AI",
  reasoning: "Steps",
  user: "You",
  assistant: "Assistant",
};

describe("ChatSurface", () => {
  afterEach(cleanup);

  it("draws turns with reasoning, sources and actions, and streams", () => {
    render(
      <ChatSurface
        isStreaming
        labels={LABELS}
        onSend={() => {}}
        messages={[
          { id: "1", role: "user", text: "Where is my order?" },
          {
            id: "2",
            role: "assistant",
            text: "It ships Thursday.",
            reasoning: [{ key: "s1", label: "Looked up order", content: "2048" }],
            sources: [{ key: "a", title: "Order 2048", href: "https://example.com/o/2048" }],
          },
          { id: "3", role: "user", text: "Thanks" },
          { id: "4", role: "assistant", text: "You're" },
        ]}
      />,
    );
    expect(screen.getAllByRole("article", { name: "You" })).toHaveLength(2);
    expect(screen.getByText("Steps")).toBeTruthy();
    expect(screen.getByText("Order 2048")).toBeTruthy();
    expect(screen.getByText("composer").dataset["status"]).toBe("streaming");
    // the finished answer has actions; the one being written has none yet
    const [done, writing] = screen.getAllByRole("article", { name: "Assistant" });
    expect(done?.querySelectorAll("button").length).toBeGreaterThan(0);
    expect(writing?.querySelectorAll("button").length).toBe(0);
  });

  it("offers starters while empty and sends a starter's prompt", () => {
    const onSend = vi.fn();
    render(
      <ChatSurface
        labels={LABELS}
        onSend={onSend}
        messages={[]}
        suggestions={[{ id: "track", title: "Track my order", prompt: "Where is order 2048?" }]}
      />,
    );
    fireEvent.click(screen.getByRole("button", { name: /Track my order/ }));
    expect(onSend).toHaveBeenCalledWith("Where is order 2048?");
  });

  it("draws a turn's parts in order and answers a tool approval", () => {
    const onApprovalResponse = vi.fn();
    render(
      <ChatSurface
        labels={LABELS}
        onSend={() => {}}
        onApprovalResponse={onApprovalResponse}
        toolLabels={{ orders_order_cancel: "Cancel order" }}
        messages={[
          {
            id: "1",
            role: "assistant",
            text: "Cancelling 2048.",
            reasoning: [{ key: "ignored", label: "Ignored", content: "ignored" }],
            parts: [
              { type: "reasoning", text: "Found order 2048" },
              { type: "text", text: "Cancelling 2048." },
              {
                type: "tool-orders_order_cancel",
                toolCallId: "call-1",
                state: "approval-requested",
                input: { orderId: "2048" },
                approval: { id: "appr-1" },
              },
            ],
          },
        ]}
      />,
    );
    expect(screen.getByText("Steps")).toBeTruthy();
    expect(screen.queryByText("Ignored")).toBeNull();
    expect(screen.getByText("Cancelling 2048.")).toBeTruthy();
    fireEvent.click(screen.getByRole("button", { name: "Approve" }));
    expect(onApprovalResponse).toHaveBeenCalledWith("appr-1", true);
  });

  it("hands its onSend and onAnswer to the default part renderers", () => {
    const onSend = vi.fn();
    const onAnswer = vi.fn();
    render(
      <ChatSurface
        labels={LABELS}
        onSend={onSend}
        onAnswer={onAnswer}
        messages={[
          {
            id: "1",
            role: "assistant",
            text: "",
            parts: [
              {
                type: "data-tamo-question",
                data: {
                  id: "q1",
                  prompt: "Which branch?",
                  choices: [{ value: "olaya", label: "Olaya" }],
                },
              },
              { type: "data-tamo-suggestions", data: { items: ["Show last month"] } },
            ],
          },
        ]}
      />,
    );
    expect(screen.getByRole("radio", { name: "Olaya" })).toBeTruthy();
    fireEvent.click(screen.getByRole("button", { name: /Show last month/ }));
    expect(onSend).toHaveBeenCalledWith("Show last month");
  });

  it("draws a text-only turn as before", () => {
    render(
      <ChatSurface
        labels={LABELS}
        onSend={() => {}}
        messages={[{ id: "1", role: "assistant", text: "Hello there." }]}
      />,
    );
    const [answer] = screen.getAllByRole("article", { name: "Assistant" });
    expect(answer?.textContent).toContain("Hello there.");
    expect(answer?.querySelector("details")).toBeNull();
  });
});
