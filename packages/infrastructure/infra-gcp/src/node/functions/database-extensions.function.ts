/**
 * Stackra file contract:
 * Purpose: `databaseExtensions(server, options, opts)`, the building block that creates a Cloud SQL server's planned
 *          Postgres extensions before any migration: the built-in admin user `stackra_admin` (a `cloudsqlsuperuser`
 *          member) with the deploy job's password, a copy of that password in Secret Manager replicated in the
 *          server's region only, a service account that may read that one secret (and, without a private IP, connect
 *          through Cloud SQL), and a Cloud Run job that runs `createExtensionsScript` in a pinned Postgres client image.
 *          The job runs to completion inside the apply (`runExecutionToken`), so a failed run fails the deploy, and
 *          runs again only when the extensions, the image or the server change. On a private IP it reaches the server
 *          over direct VPC egress with TLS required; otherwise through the Cloud SQL volume's connector socket.
 * Boundary: declares resources only, under the runtime's component and provider; `gcpRuntime` calls it when the
 *           server's services name extensions. The password arrives as a Pulumi secret input (generated by the deploy
 *           job and kept in the vault, ADR 0493 decision 4, ADR 0525), goes only to the user and the secret, and is
 *           never logged, returned or put in the job: the job reads it from Secret Manager at run time.
 * Runtime: node
 * Governing contract: ADR 0160 (decision 2, notes of 2026-11-03 and 2026-11-26: infra pre-creates the extensions with
 *                     the admin login before migrations), ADR 0238, ADR 0186 (in-region copies), ADR 0173.
 */
/* oxlint-disable no-new -- reason: Pulumi registers a resource when it is constructed; that is the point */
import { createHash } from "node:crypto";

import * as gcp from "@pulumi/gcp";
import * as pulumi from "@pulumi/pulumi";
import { createExtensionsScript } from "@stackra/runway";
import type { PostgresExtension } from "@stackra/runway";

import { DATABASE_SETUP_SETTINGS } from "#core/constants/database-setup-settings.constant";
import { serviceAccountId } from "#core/functions/service-account-id.function";

/** The server the extensions are created on, and where it lives. */
type Server = {
  /** The deployment prefix (`acme-production`), which names every resource here. */
  readonly prefix: string;
  /** The GCP project id. */
  readonly project: string;
  /** The server's region; the secret's only replica and the job live there too. */
  readonly region: string;
  /** The extensions the server's services name. */
  readonly extensions: readonly PostgresExtension[];
  /** The Cloud SQL instance. */
  readonly instance: gcp.sql.DatabaseInstance;
  /** The VPC the server's private IP is on, or `null` when it is reached through the connector. */
  readonly network: pulumi.Input<string> | null;
  /** Labels every resource carries. */
  readonly labels: Readonly<Record<string, string>>;
};

/**
 * Declares the admin login, its secret, the job's account and the job that creates `server.extensions`.
 *
 * @param options.adminPassword - the admin user's password, as a Pulumi secret.
 * @param options.subnet - the subnet the job's direct VPC egress takes addresses from on a private server; the
 *        network's same-named subnet when absent.
 * @param options.image - the Postgres client image, for a registry other than Docker Hub.
 * @example
 * const job = databaseExtensions({ prefix, project, region, extensions, instance, network, labels }, { adminPassword }, scoped);
 */
export function databaseExtensions(
  server: Server,
  options: {
    readonly adminPassword: pulumi.Input<string>;
    readonly subnet?: pulumi.Input<string> | undefined;
    readonly image?: string | undefined;
  },
  opts: pulumi.CustomResourceOptions,
): gcp.cloudrunv2.Job {
  const { prefix, project, region, instance, labels } = server;
  const password = pulumi.secret(options.adminPassword);
  const user = new gcp.sql.User(
    `${prefix}-admin`,
    {
      project,
      instance: instance.name,
      name: DATABASE_SETUP_SETTINGS.adminUser,
      password,
      // Postgres refuses to drop a role that owns objects; a stack change never tries.
      deletionPolicy: "ABANDON",
    },
    opts,
  );
  const secret = new gcp.secretmanager.Secret(
    `${prefix}-db-admin`,
    {
      project,
      secretId: `${prefix}-db-admin`,
      replication: { userManaged: { replicas: [{ location: region }] } },
      labels: { ...labels },
    },
    opts,
  );
  const version = new gcp.secretmanager.SecretVersion(
    `${prefix}-db-admin`,
    { secret: secret.id, secretData: password },
    opts,
  );
  const account = new gcp.serviceaccount.Account(
    `${prefix}-${DATABASE_SETUP_SETTINGS.accountPurpose}`,
    {
      project,
      accountId: serviceAccountId(prefix, DATABASE_SETUP_SETTINGS.accountPurpose),
      displayName: `${prefix} database extensions job`,
    },
    opts,
  );
  const member = pulumi.interpolate`serviceAccount:${account.email}`;
  const grants: pulumi.Resource[] = [
    new gcp.secretmanager.SecretIamMember(
      `${prefix}-db-admin-reader`,
      { project, secretId: secret.secretId, role: "roles/secretmanager.secretAccessor", member },
      opts,
    ),
  ];
  const isPrivate = server.network !== null;
  if (!isPrivate)
    grants.push(
      new gcp.projects.IAMMember(
        `${prefix}-dbext-sql-client`,
        { project, role: "roles/cloudsql.client", member },
        opts,
      ),
    );

  const script = createExtensionsScript(server.extensions);
  const image = options.image ?? DATABASE_SETUP_SETTINGS.image;
  const host = isPrivate
    ? instance.privateIpAddress
    : pulumi.interpolate`${DATABASE_SETUP_SETTINGS.socketPath}/${instance.connectionName}`;
  // A new token runs the job again: when the extensions, the image or the server change, never otherwise.
  const token = pulumi.all([instance.connectionName]).apply(([connection]) =>
    createHash("sha256")
      .update([connection ?? "", image, isPrivate ? "private" : "connector", script].join("\n"))
      .digest("hex")
      .slice(0, 12),
  );
  return new gcp.cloudrunv2.Job(
    `${prefix}-extensions`,
    {
      project,
      location: region,
      name: `${prefix}-extensions`,
      deletionProtection: false,
      labels: { ...labels },
      runExecutionToken: token,
      template: {
        taskCount: 1,
        template: {
          serviceAccount: account.email,
          maxRetries: 0,
          timeout: DATABASE_SETUP_SETTINGS.timeout,
          containers: [
            {
              image,
              commands: ["sh", "-c"],
              args: [script],
              envs: [
                { name: "PGHOST", value: host },
                { name: "PGPORT", value: "5432" },
                { name: "PGUSER", value: DATABASE_SETUP_SETTINGS.adminUser },
                // The connector socket is already encrypted; a private IP gets TLS, which the server requires.
                ...(isPrivate ? [{ name: "PGSSLMODE", value: "require" }] : []),
                { name: "PGCONNECT_TIMEOUT", value: "10" },
                {
                  name: "PGPASSWORD",
                  valueSource: {
                    secretKeyRef: { secret: secret.secretId, version: version.version },
                  },
                },
              ],
              ...(isPrivate
                ? {}
                : {
                    volumeMounts: [
                      { name: "cloudsql", mountPath: DATABASE_SETUP_SETTINGS.socketPath },
                    ],
                  }),
            },
          ],
          ...(isPrivate
            ? {
                vpcAccess: {
                  egress: "PRIVATE_RANGES_ONLY",
                  networkInterfaces: [
                    {
                      network: server.network ?? undefined,
                      ...(options.subnet === undefined ? {} : { subnetwork: options.subnet }),
                    },
                  ],
                },
              }
            : {
                volumes: [
                  { name: "cloudsql", cloudSqlInstance: { instances: [instance.connectionName] } },
                ],
              }),
        },
      },
    },
    { ...opts, dependsOn: [user, version, ...grants] },
  );
}
