#!/usr/bin/env node
/**
 * Stackra file contract:
 * Purpose: `pnpm secrets:catalog` (ADR 0525 decision 7): keep `catalog.yaml` in a `figentra/secrets` checkout in step
 *   with the secret files and the names `runway.yaml` declares. Every name gets an owner, a purpose, a kind
 *   (generated, minted or human), a rotation period and, for a human value, an expiry. `--check` fails on a gap.
 * Boundary: file names and YAML only; it never decrypts, so it needs no key and sees no value.
 * Runtime: node
 * Governing contract: ADR 0525.
 * Input: `--repo <dir>` (a checkout of figentra/secrets; default `$STACKRA_SECRETS_DIR` or `~/.stackra/secrets`),
 *   `--check`, and `runway.yaml` paths as positionals (their `secrets` names must exist).
 * Output: writes `catalog.yaml` (kept fields survive), or with `--check` prints one problem per line by name.
 * Secrets: none; names only.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { parse, stringify } from "yaml";
import { NAME_RX, listNames } from "./secrets-sops.mjs";

export const KINDS = ["generated", "minted", "human"];
const HEADER =
  "# Generated by `pnpm secrets:catalog` (ADR 0525). Names only. `scopes` is rewritten from the files; owner,\n" +
  "# purpose, kind (generated, minted, human), rotateDays and expires are yours and are kept.\n";

/** Every SCREAMING_SNAKE name under any `secrets` key of a runway.yaml document, as a list item or a map key. */
export function declaredNames(doc) {
  const out = new Set();
  const collect = (node) => {
    if (typeof node === "string" && NAME_RX.test(node)) out.add(node);
    else if (Array.isArray(node)) node.forEach(collect);
    else if (node && typeof node === "object")
      for (const [k, v] of Object.entries(node)) {
        if (NAME_RX.test(k)) out.add(k);
        collect(v);
      }
  };
  const walk = (node) => {
    if (Array.isArray(node)) node.forEach(walk);
    else if (node && typeof node === "object")
      for (const [k, v] of Object.entries(node)) (k === "secrets" ? collect : walk)(v);
  };
  walk(doc);
  return out;
}

/** The new catalog: every file's name with its scopes, kept fields from `old`, entries with no file dropped. */
export function buildCatalog(files, old = {}) {
  const catalog = {};
  for (const { scope, name } of files) {
    catalog[name] ??= { ...old[name], scopes: [] };
    catalog[name].scopes.push(scope);
  }
  return Object.fromEntries(Object.entries(catalog).toSorted(([a], [b]) => a.localeCompare(b)));
}

/** Value-free problems: a catalog entry missing a field, a file not in the catalog, a declared name with no file. */
export function checkCatalog(catalog, files, declared = new Set()) {
  const problems = [];
  const fileNames = new Set(files.map((f) => f.name));
  for (const name of fileNames)
    if (!catalog[name]) problems.push(`${name}: has a file but no catalog entry`);
  for (const [name, e] of Object.entries(catalog)) {
    if (!fileNames.has(name)) problems.push(`${name}: in the catalog but has no file`);
    for (const field of ["owner", "purpose"])
      if (!e?.[field]) problems.push(`${name}: no ${field}`);
    if (!KINDS.includes(e?.kind)) problems.push(`${name}: kind must be one of ${KINDS.join(", ")}`);
    if (!Number.isInteger(e?.rotateDays)) problems.push(`${name}: no rotateDays`);
    if (e?.kind === "human" && !/^\d{4}-\d{2}-\d{2}$/.test(String(e?.expires ?? "")))
      problems.push(`${name}: a human value needs expires (YYYY-MM-DD)`);
  }
  for (const name of declared)
    if (!fileNames.has(name)) problems.push(`${name}: declared in runway.yaml but has no file`);
  return problems.toSorted();
}

/** Write or check the catalog; returns the exit code. */
export function main(
  argv,
  { env = process.env, home = homedir(), write = (s) => process.stdout.write(s) } = {},
) {
  const say = (s) => write(`${s}\n`);
  let args;
  try {
    args = parseArgs({
      args: argv,
      allowPositionals: true,
      options: { repo: { type: "string" }, check: { type: "boolean" } },
    });
  } catch {
    say("usage: pnpm secrets:catalog [--repo <dir>] [--check] [runway.yaml…]");
    return 2;
  }
  const { values: o, positionals } = args;
  const repo = o.repo ?? env.STACKRA_SECRETS_DIR ?? join(home, ".stackra", "secrets");
  if (!existsSync(repo)) {
    say(`secrets-catalog: no checkout at ${repo} (gh repo clone figentra/secrets ${repo})`);
    return 1;
  }
  const path = join(repo, "catalog.yaml");
  const old = existsSync(path) ? (parse(readFileSync(path, "utf8")) ?? {}) : {};
  const files = listNames(repo);
  const declared = new Set(
    positionals.flatMap((p) => [...declaredNames(parse(readFileSync(p, "utf8")))]),
  );
  const catalog = buildCatalog(files, old);
  if (o.check) {
    const problems = checkCatalog(old, files, declared);
    for (const p of problems) say(p);
    say(problems.length ? `secrets-catalog: ${problems.length} problem(s)` : "secrets-catalog: ok");
    return problems.length ? 1 : 0;
  }
  writeFileSync(path, HEADER + stringify(catalog));
  say(`secrets-catalog: ${Object.keys(catalog).length} names written to catalog.yaml`);
  return 0;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  process.exitCode = main(process.argv.slice(2));
