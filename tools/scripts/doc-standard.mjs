/**
 * Stackra file contract:
 * Purpose: the doc-standard check (ADR 0007, amended 2026-10-21). For every tracked source file in packages, services,
 *          apps and workers it requires the contract header, a TSDoc block on exported symbols, exported interface and
 *          type-literal members, public and protected class members and DI token constants, and it rejects types
 *          inside doc tags. It parses with the TypeScript compiler API and never type-checks.
 * Boundary: reads tracked files and reports findings; it never edits a file and never judges the wording of a block.
 * Runtime: node
 * Governing contract: ADR 0007 (amendment 2026-10-21), ADR 0128. Run by `pnpm validate`.
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

import { KIND_FOLDERS } from "./structure.mjs";

const ROOT = fileURLToPath(new URL("../../", import.meta.url));

/** The marker every contract header carries (ADR 0007, decision 1). */
const CONTRACT = "Stackra file contract:";
/** First-line marker of a generated migration, which the doc-standard check skips. */
const GENERATED_MIGRATION = /^\/\/ generated by stackra db diff\r?\n/;
const MIGRATION = KIND_FOLDERS.find((k) => k.folder === "migrations");
/** True for a file in a `migrations/` folder with the `.migration` suffix (kind-folder definition). */
const isMigration = (path) =>
  path.includes(`/${MIGRATION.folder}/`) && new RegExp(`\\.${MIGRATION.suffix}\\.tsx?$`).test(path);
/** The header fields ADR 0007 requires, in order. */
const FIELDS = ["Purpose", "Boundary", "Runtime", "Governing contract"];
/** The only values the `Runtime:` field may take. */
const RUNTIMES = ["node", "browser", "worker", "react-native", "isomorphic"];
/** A tag whose braces hold a type: TypeScript owns types, so a doc tag never carries one. */
const TYPED_TAG = /@(?:param|arg|argument|returns?|throws|property|prop)\s*\{/g;
/** A summary shorter than this many words is a label, not a purpose sentence. */
const MIN_SUMMARY_WORDS = 3;

/**
 * True for the source files this rule governs: a `src/` file of a package, service or app, minus tests, generated code
 * and declaration files.
 * @param path - repository-relative path, forward slashes.
 */
export function isInScope(path) {
  if (!/^(packages|services|apps|workers)\/.+\/src\/.+\.tsx?$/.test(path)) return false;
  return !/(__tests__\/|\.test\.tsx?$|\.d\.ts$|\/generated\/|encore\.gen\/)/.test(path);
}

/**
 * Check one source file and return its findings as `path:line: message` strings.
 * @param path - repository-relative path; picks the parser script kind from its extension.
 * @param text - the file's full contents.
 */
export function checkFile(path, text) {
  // Generated migrations carry no contract header and are rewritten by `stackra db diff`.
  if (isMigration(path) && GENERATED_MIGRATION.test(text)) return [];
  const kind = path.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS;
  const sf = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true, kind);
  const at = (pos) => `${path}:${sf.getLineAndCharacterOfPosition(pos).line + 1}`;
  const findings = [];

  const headerProblem = checkHeader(text);
  if (headerProblem) findings.push(`${path}:1: ${headerProblem}`);

  for (const match of text.matchAll(TYPED_TAG)) {
    const line = sf.getLineAndCharacterOfPosition(match.index).line + 1;
    findings.push(
      `${path}:${line}: ${match[0]} carries a type; name the parameter and describe it, TypeScript owns the type (ADR 0007)`,
    );
  }

  for (const stmt of sf.statements) {
    if (!hasModifier(stmt, ts.SyntaxKind.ExportKeyword)) continue;
    if (ts.isVariableStatement(stmt)) {
      for (const decl of stmt.declarationList.declarations) {
        const name = decl.name.getText(sf);
        if (isDefineToken(decl)) {
          const doc = docOf(sf, text, stmt);
          const problem = !doc
            ? "has no TSDoc block"
            : !(/resol/i.test(doc) && /provid/i.test(doc))
              ? "is a DI token whose TSDoc must say what resolves to it and who provides it"
              : summaryProblem(doc);
          if (problem) findings.push(`${at(stmt.getStart(sf))}: export const ${name} ${problem}`);
        } else {
          requireDoc(findings, at, sf, text, stmt, `export const ${name}`);
        }
      }
      continue;
    }
    if (
      ts.isFunctionDeclaration(stmt) ||
      ts.isClassDeclaration(stmt) ||
      ts.isInterfaceDeclaration(stmt) ||
      ts.isTypeAliasDeclaration(stmt) ||
      ts.isEnumDeclaration(stmt) ||
      ts.isModuleDeclaration(stmt)
    ) {
      const name = stmt.name?.getText(sf) ?? "default";
      requireDoc(findings, at, sf, text, stmt, `export ${name}`);
    }
    if (ts.isInterfaceDeclaration(stmt)) {
      requireMembers(findings, at, sf, text, stmt.name.text, signatureMembers(stmt.members));
    }
    if (ts.isTypeAliasDeclaration(stmt) && ts.isTypeLiteralNode(stmt.type)) {
      requireMembers(findings, at, sf, text, stmt.name.text, signatureMembers(stmt.type.members));
    }
    if (ts.isClassDeclaration(stmt)) {
      const publicMembers = stmt.members.filter(
        (m) =>
          (ts.isPropertyDeclaration(m) ||
            ts.isMethodDeclaration(m) ||
            ts.isGetAccessorDeclaration(m) ||
            ts.isSetAccessorDeclaration(m)) &&
          !isInternalMember(m),
      );
      requireMembers(findings, at, sf, text, stmt.name?.text ?? "default", publicMembers);
    }
  }
  return findings;
}

/**
 * The header is the file's first comment, before any import, and it names every field with a known runtime (ADR 0007,
 * decision 1). Returns the problem, or undefined when the header is well formed.
 * @param text - the file's full contents.
 */
function checkHeader(text) {
  const first = ts.getLeadingCommentRanges(text, 0)?.[0];
  const header = first ? text.slice(first.pos, first.end) : "";
  if (!header.startsWith("/**") || !header.includes(CONTRACT))
    return `missing the Stackra file contract header before the imports (ADR 0007)`;
  for (const field of FIELDS) {
    if (!new RegExp(`^\\s*\\*?\\s*${field}:`, "m").test(header))
      return `contract header has no "${field}:" field (ADR 0007)`;
  }
  const runtime = /^\s*\*?\s*Runtime:[ \t]*(.*)$/m.exec(header)?.[1].trim();
  if (!RUNTIMES.includes(runtime))
    return `contract header Runtime must be one of ${RUNTIMES.join(", ")} (ADR 0007)`;
  return undefined;
}

/**
 * The TSDoc block that documents `node`: the last `/** … *\/` block before it, with only line comments and whitespace
 * between them. A contract header never counts as a doc block.
 * @param sf - the parsed source file.
 * @param text - the file's full contents.
 * @param node - the declaration or member to document.
 * @returns the block's text, or undefined when there is none.
 */
function docOf(sf, text, node) {
  const comments = ts.getLeadingCommentRanges(text, node.pos) ?? [];
  const block = comments.filter((c) => text.startsWith("/**", c.pos)).at(-1);
  if (!block) return undefined;
  const between = text.slice(block.end, node.getStart(sf)).replace(/\/\/[^\n]*/g, "");
  if (between.trim() !== "") return undefined;
  const body = text.slice(block.pos, block.end);
  return body.includes(CONTRACT) ? undefined : body;
}

/**
 * The summary (the text before the first tag) must be a sentence, not a label.
 * @param doc - the block's text.
 * @returns a problem description, or undefined.
 */
function summaryProblem(doc) {
  const lines = doc
    .replace(/^\/\*\*|\*\/$/g, "")
    .split("\n")
    .map((line) => line.replace(/^\s*\*?\s?/, ""));
  // Only a tag that starts a line ends the summary; `@stackra/logger` mid-sentence is prose.
  const tagAt = lines.findIndex((line) => /^@\w/.test(line.trim()));
  const summary = (tagAt === -1 ? lines : lines.slice(0, tagAt)).join(" ").trim();
  return summary.split(/\s+/).filter(Boolean).length < MIN_SUMMARY_WORDS
    ? "has a TSDoc block without a purpose sentence (ADR 0007)"
    : undefined;
}

/**
 * Push a finding unless `node` carries a TSDoc block with a purpose sentence.
 * @param findings - the array the finding is pushed to.
 * @param at - formats a node position as `path:line`.
 * @param sf - the parsed source file.
 * @param text - the file's full contents.
 * @param node - the node that must be documented.
 * @param label - how the finding names the node.
 */
function requireDoc(findings, at, sf, text, node, label) {
  const doc = docOf(sf, text, node);
  const problem = doc ? summaryProblem(doc) : "has no TSDoc block (ADR 0007)";
  if (problem) findings.push(`${at(node.getStart(sf))}: ${label} ${problem}`);
}

/**
 * Require a TSDoc block on each member of an owner (an exported interface, type literal or class).
 * @param findings - the array the findings are pushed to.
 * @param at - formats a node position as `path:line`.
 * @param sf - the parsed source file.
 * @param text - the file's full contents.
 * @param owner - the owner's name, used in the finding.
 * @param members - the members to check.
 */
function requireMembers(findings, at, sf, text, owner, members) {
  for (const member of members) {
    const name = member.name?.getText(sf) ?? "[computed]";
    requireDoc(findings, at, sf, text, member, `${owner}.${name}`);
  }
}

/**
 * The property and method signatures of an interface or type literal.
 * @param members - the owner's members.
 */
function signatureMembers(members) {
  return members.filter((m) => ts.isPropertySignature(m) || ts.isMethodSignature(m));
}

/**
 * @param node - a statement or class member.
 * @param kind - a modifier kind to look for.
 */
function hasModifier(node, kind) {
  return node.modifiers?.some((m) => m.kind === kind) ?? false;
}

/**
 * A class member that is not part of the exported surface: `private` or a `#name`.
 * @param member - a class member.
 */
function isInternalMember(member) {
  return (
    hasModifier(member, ts.SyntaxKind.PrivateKeyword) ||
    member.name?.kind === ts.SyntaxKind.PrivateIdentifier
  );
}

/**
 * True when a variable is a DI token, `defineToken(...)` (ADR 0007 amendment, decision 2).
 * @param decl - a variable declaration.
 */
function isDefineToken(decl) {
  const init = decl.initializer;
  return (
    init !== undefined &&
    ts.isCallExpression(init) &&
    ts.isIdentifier(init.expression) &&
    init.expression.text === "defineToken"
  );
}

/**
 * Run the check over every governed tracked file. Exits 1 with the findings, 0 when clean.
 */
function main() {
  const files = execFileSync(
    "git",
    ["ls-files", "--cached", "--others", "--exclude-standard", "--deduplicate"],
    { cwd: ROOT, encoding: "utf8" },
  )
    .split("\n")
    .filter((p) => isInScope(p) && existsSync(join(ROOT, p)));
  const findings = files.flatMap((p) => checkFile(p, readFileSync(join(ROOT, p), "utf8")));
  for (const finding of findings) console.error(finding);
  if (findings.length) {
    console.error(`\n${findings.length} doc-standard finding(s) in ${files.length} file(s).`);
    process.exit(1);
  }
  console.log(`doc-standard: ${files.length} source file(s) clean.`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
